def _invalid(message: str) -> RegistryError:
    return RegistryError(message, code="invalid_argument")


def _reactant_row(component: dict[str, Any], index: int) -> int:
    """A stored reactant's row number (its ``row``, else its position)."""
    row = component.get("row")
    return row if isinstance(row, int) and not isinstance(row, bool) else index + 1


def _reactant_name(component: dict[str, Any]) -> str | None:
    """A stored reactant's name, else its formula, else None."""
    for key in ("name", "formula"):
        value = component.get(key)
        if isinstance(value, str) and value.strip():
            return value.strip()
    return None


def _route_choice(run: Any, product: str | None) -> dict[str, Any]:
    """One ``route`` ``choices`` entry (protocol.py, "Synthesis routes")."""
    by = getattr(run, "limiting_by", None)
    return {
        "experiment_ref": run.experiment_ref,
        "experiment_code": run.experiment_code,
        "compound": getattr(run, "compound", "") or product or "",
        "row": getattr(run, "limiting_row", None),
        "by": by if by in protocol.LIMITING_BY else None,
        "auto_row": getattr(run, "auto_row", None),
        "ambiguous": bool(getattr(run, "ambiguous", False)),
        "candidates": [{"row": c.row, "name": c.name, "eq": c.eq, "mass": c.mass}
                       for c in getattr(run, "candidates", ())],
    }


def _inchi_version() -> str:
    try:
        return str(Chem.GetInchiVersion())
    except Exception:  # noqa: BLE001
        return ""


def chemistry_fingerprint() -> str:
    """``rdkit=<version>;inchi=<version>;keyalg=<chem.KEY_ALGORITHM>``: what the
    registry keys depend on. A change means keys may now come out differently."""
    return f"rdkit={rdkit.__version__};inchi={_inchi_version()};keyalg={chem.KEY_ALGORITHM}"


def ignored_stereo_message(items: Iterable[str]) -> str:
    """Why a structure with stereo outside its keys is not registered silently."""
    listed = "; ".join(items)
    return (
        f"The drawing contains stereo that is NOT part of the registry keys: {listed}. "
        "Registering it would give stereoisomers that differ only in these features the "
        "same ID. Nothing was registered. If that is acceptable, accept these items "
        "explicitly (accept_ignored_stereo / --accept-ignored-stereo)."
    )


def _name_ids(ids: list[str]) -> str:
    named = ", ".join(ids[:_NAMED_IN_MESSAGES])
    if len(ids) > _NAMED_IN_MESSAGES:
        named += f" and {len(ids) - _NAMED_IN_MESSAGES} more"
    return named


@dataclass
class _JournalCheck:
    """Comparison of the issued-ID journal(s) with the database."""

    files: list[journal_mod.JournalFile]
    entries: list[dict[str, Any]]                  # own lines: merged, deduplicated, journal order
    missing_register: list[str] = field(default_factory=list)   # IDs absent from the DB
    missing_retire: list[str] = field(default_factory=list)     # journalled retirements not in the DB
    conflicts: list[str] = field(default_factory=list)          # IDs that name something else in the DB
    already_present: int = 0

    @property
    def shared(self) -> list[journal_mod.JournalFile]:
        """The journal files that also hold lines of other registries."""
        return [jf for jf in self.files if jf.foreign]

    @property
    def other_registries(self) -> list[str]:
        return sorted({rid for jf in self.files for rid in jf.foreign})

    @property
    def stale(self) -> bool:
        return bool(self.missing_register or self.missing_retire)


def batch_to_dict(batch: BatchRecord, with_molfile: bool = False) -> dict[str, Any]:
    """All :class:`BatchRecord` fields plus ``retired``; ``molfile`` only on request."""
    d = dataclasses.asdict(batch)
    d["retired"] = batch.retired
    if not with_molfile:
        d.pop("molfile", None)
    return d


def key_digest(norm: Normalized) -> str:
    """SHA-256 (hex) of exactly what selects a CORE_STEREO: the core key, the
    stereo key and the stereo mode. Two structures get the same CORE_STEREO if
    and only if their digests are equal. It is not stored and is not a key
    itself; callers use it to check that the compound being registered is the
    one a user confirmed (the InChIKey alone cannot tell, for example, which
    centre of a 'mixed' drawing is the racemic one)."""
    text = "\n".join((norm.core_key, norm.stereo_key, norm.stereo_mode))
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def name_dict(record: NameRecord | None) -> dict[str, str] | None:
    """``{"text", "updated_at", "source"}`` of a stored name, or None."""
    if record is None:
        return None
    return {"text": record.text, "updated_at": record.updated_at, "source": record.source}


def clean_name(value: object) -> str | None:
    """A name as it is stored: stripped text of one line without control
    characters, at most :data:`protocol.MAX_NAME_TEXT` characters; None stays
    None (remove the name). Anything else raises ``invalid_argument``."""
    if value is None:
        return None
    if not isinstance(value, str):
        raise _invalid(f"A name must be text, got {type(value).__name__}.")
    text = value.strip()
    if not text:
        raise _invalid("The name is blank. To remove a stored name, give no name "
                       "(null / --remove) instead.")
    if len(text) > protocol.MAX_NAME_TEXT:
        raise _invalid(f"The name is too long ({len(text)} characters, limit "
                       f"{protocol.MAX_NAME_TEXT}).")
    if any(unicodedata.category(ch) == "Cc" or ch in "\u2028\u2029" for ch in text):
        raise _invalid("A name must be one line of text without control characters.")
    return text


def yield_dict(record: YieldRecord | None) -> dict[str, Any] | None:
    """``{"isolated", "analytical", "updated_at"}`` of a stored yield, or None."""
    if record is None:
        return None
    return {"isolated": record.isolated, "analytical": record.analytical,
            "updated_at": record.updated_at}


def clean_yield(kind: str, value: object) -> float | None:
    """A yield as it is stored: None (none shown), or a real number of percent
    from 0 to :data:`protocol.MAX_YIELD_PERCENT` rounded to two decimals.
    Anything else (text, true/false, NaN, infinity, out of range) raises
    ``invalid_argument``."""
    if value is None:
        return None
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise _invalid(f"The {kind} yield must be a number of percent or none, got {value!r}.")
    number = float(value)
    if not 0 <= number <= protocol.MAX_YIELD_PERCENT:     # also refuses NaN and infinity
        raise _invalid(f"The {kind} yield must be from 0 to {protocol.MAX_YIELD_PERCENT} "
                       f"percent, got {value!r}.")
    return round(number, 2) + 0.0                           # + 0.0: never -0.0


def clean_reaction(value: object) -> dict[str, Any]:
    """The ``reaction`` of ``set_reaction`` as it is stored: checked and
    completed exactly as the host checks it (protocol.py, "Reactions"), with
    every documented key present. Anything else raises ``invalid_argument``."""
    reader = protocol._ReactionReader(protocol._Params({}, "set_reaction", 0))
    try:
        return reader.read(value)
    except protocol.ProtocolError as exc:
        raise _invalid(exc.message) from None


