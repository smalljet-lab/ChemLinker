    # ------------------------------------------------------------------ maintenance
    def rekey_check(self, accept: bool = False) -> dict[str, Any]:
        """Recompute the keys of every batch from its stored molfile and check
        that they still resolve to the same CORE_STEREO.

        Each molfile is first normalised as-is; if the resulting mode differs
        from the stored one and the stored one is a mode a user can choose
        (abs/rac/rel/undefined), it is normalised again with the stored mode
        as override (it was registered with an override or a default mode).

        Without ``accept`` nothing is written. With ``accept=True`` and ZERO
        mismatches, the current chemistry fingerprint is stored, which lifts
        the ``chemistry_version_changed`` block on ``register``; with
        mismatches nothing is stored (``accepted`` is false). The result has
        ``chemistry_fingerprint: {"stored", "current", "changed"}`` (as
        after the call) and ``accepted``.
        """
        result = self._rekey_scan()
        accepted = False
        if accept and not result["mismatches"]:
            state = self._chemistry_state()
            if not state["supported"]:
                raise RegistryError("This storage backend does not record the chemistry version.",
                                    code="invalid_argument")
            self.repo.set_meta(FINGERPRINT_KEY, state["current"])  # type: ignore[attr-defined]
            self._chemistry_cache = None
            accepted = True
        state = self._chemistry_state()
        result["chemistry_fingerprint"] = {"stored": state["stored"], "current": state["current"],
                                           "changed": bool(state["changed"])}
        result["accepted"] = accepted
        return result

    def chemistry_upgrade(self) -> dict[str, Any]:
        """What an upgrade of the program does about the chemistry guard,
        without asking anything: when the chemistry version changed, run
        :meth:`rekey_check` with ``accept=True``.

        Returns ``{"status", "message", "checked", "mismatches",
        "chemistry_fingerprint"}``. ``status`` is

        * ``"current"`` - the version did not change; nothing was checked or
          written;
        * ``"accepted"`` - it changed, every stored structure still gives the
          same keys, and the new version is recorded (registering works);
        * ``"blocked"`` - it changed and ``mismatches`` (as in
          :meth:`rekey_check`) lists structures whose keys differ now.
          Nothing was written and registering stays blocked.

        ``message`` says the same in words, with what to do when blocked.
        """
        state = self._chemistry_state()
        fingerprint = {"stored": state["stored"], "current": state["current"],
                       "changed": bool(state["changed"])}
        if not state["supported"] or not state["changed"]:
            return {"status": "current", "checked": 0, "mismatches": [],
                    "chemistry_fingerprint": fingerprint,
                    "message": "The chemistry version did not change; nothing to check."}
        result = self.rekey_check(accept=True)
        mismatches = result["mismatches"]
        if result["accepted"]:
            status = "accepted"
            message = (f"{result['checked']} structure(s) checked, keys unchanged, new "
                       f"chemistry version accepted ({result['chemistry_fingerprint']['current']}).")
        else:
            status = "blocked"
            named = _name_ids([m["id"] for m in mismatches])
            message = (
                f"{result['checked']} structure(s) checked with the new chemistry version "
                f"({state['current']}): {len(mismatches)} no longer give the same keys "
                f"({named}). Nothing was changed, and registering stays blocked, because a "
                "known compound could get a second ID. Install the previous program version "
                "again to keep registering, and report this to the maintainers with the "
                "output of 'compound-registry rekey-check'.")
        return {"status": status, "checked": result["checked"], "mismatches": mismatches,
                "chemistry_fingerprint": result["chemistry_fingerprint"], "message": message}

    def _rekey_scan(self) -> dict[str, Any]:
        """The read-only part of :meth:`rekey_check`."""
        checked = ok = 0
        mismatches: list[dict[str, Any]] = []
        for batch in self.repo.iter_batches(include_retired=True):
            checked += 1
            recomputed: str | None = None
            try:
                norm = chem.normalize(batch.molfile)
                if norm.stereo_mode != batch.stereo_mode and batch.stereo_mode in MODE_OVERRIDES:
                    norm = chem.normalize(batch.molfile, batch.stereo_mode)
                found = self.repo.lookup(norm)
                if found.stereo is not None:
                    recomputed = found.stereo.core_stereo_id
                if recomputed == batch.core_stereo_id:
                    ok += 1
                    continue
                if found.core is None:
                    reason = "the recomputed core key is not in the registry"
                elif found.stereo is None:
                    reason = (f"the recomputed stereo key (mode {norm.stereo_mode}) is not "
                              f"registered under core {found.core.core_no}")
                else:
                    reason = f"the recomputed keys belong to {recomputed}"
            except RegistryError as exc:
                reason = f"{exc.code}: {exc.message}"
            except Exception as exc:  # noqa: BLE001 - report, never abort the check
                reason = f"unexpected error: {type(exc).__name__}: {exc}"
            mismatches.append({"id": batch.full_id, "stored": batch.core_stereo_id,
                               "recomputed": recomputed, "reason": reason})
        return {
            "checked": checked,
            "ok": ok,
            "mismatches": mismatches,
            "rdkit_version": rdkit.__version__,
            "inchi_version": _inchi_version(),
        }

    def doctor(self) -> dict[str, Any]:
        """Configuration, database health and environment in one dict.

        Includes ``journal`` (see :meth:`journal_status`),
        ``name_generator: {"available", "label"}`` (see
        :func:`naming.generator_info`; ChemDraw is not started to find out) and
        ``chemistry_fingerprint: {"stored", "current", "changed"}``; a stale
        database, journal problems and a chemistry change are also warnings.
        ``program_version``, ``schema_version`` (of the open file),
        ``registry_id`` and ``read_only`` (the file can only be read) say
        which program looks at which registry. ``backups`` is the number of
        backup files in the backup folder, 0 when none of them is this
        registry's (:meth:`list_backups` lists exactly its own).
        """
        repo = self.repo
        journal: dict[str, Any] | None
        try:
            journal = self.journal_status()
        except RegistryError:
            journal = None  # reported by _read_warnings
        warnings = self._read_warnings()
        chem_state = self._chemistry_state()

        def call(name: str, default: Any) -> Any:
            fn = getattr(repo, name, None)
            if fn is None:
                return default
            try:
                return fn()
            except RegistryError as exc:
                warnings.append(f"{name} failed: {exc.message}")
                return default

        id_format = getattr(repo, "id_format", None)
        last_backup = None
        if hasattr(repo, "get_meta"):
            try:
                last_backup = repo.get_meta(backup_mod.LAST_BACKUP_KEY)  # type: ignore[attr-defined]
            except RegistryError as exc:
                warnings.append(f"Could not read the last backup time: {exc.message}")
        integrity = call("integrity_check", "unknown")
        if integrity not in ("ok", "unknown"):
            warnings.append(f"Database integrity check failed: {integrity}")
        # The number of backup files; whether one of them is this registry's
        # is asked newest first, which normally opens one file, not all.
        backups = backup_mod.list_backups(self.config)
        if backup_mod.newest_backup(self.config, self._registry_id()) is None:
            backups = []
            warnings.append(f"No backup exists yet in {self.config.backup_dir}.")
        db_path = Path(self.config.db_path)
        read_only = bool(getattr(repo, "read_only", False))
        if read_only:
            warnings.append(f"The registry database {db_path} cannot be written (the file or "
                            "its folder is read-only): it can be read, but nothing can be "
                            "registered or changed.")
        return {
            "program_version": __version__,
            "schema_version": getattr(repo, "schema_version", None),
            "registry_id": self._registry_id(),
            "read_only": read_only,
            "home": str(self.config.home),
            "config_path": str(self.config.config_path),
            "db_path": str(db_path),
            "db_exists": db_path.is_file(),
            "db_created_now": db_path.is_file() and not self._db_existed_at_open,
            "id_format": id_format.template if id_format is not None else self.config.id_format,
            "default_stereo_mode": self.config.default_stereo_mode,
            "stats": call("stats", {}),
            "integrity": integrity,
            "backup_dir": str(self.config.backup_dir),
            "backup_interval_hours": self.config.backup_interval_hours,
            "backup_keep": self.config.backup_keep,
            "last_backup_at": last_backup,
            "backups": len(backups),
            "rdkit_version": rdkit.__version__,
            "inchi_version": _inchi_version(),
            "chemistry_fingerprint": {"stored": chem_state["stored"],
                                      "current": chem_state["current"],
                                      "changed": bool(chem_state["changed"])},
            "journal": journal,
            "name_generator": naming.generator_info(),
            "files_folder": str(self.config.files_dir),
            "python": sys.version.split()[0],
            "warnings": list(dict.fromkeys(warnings)),
        }


