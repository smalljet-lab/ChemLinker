"""The registry service: the single entry point for the CLI and the native host.

Every public method takes plain Python values, returns plain JSON-serialisable
dicts and lists (no dataclasses, no ``Path`` objects) and raises only
:class:`~compound_registry.errors.RegistryError` subclasses.

The service decides nothing about chemistry (that is ``chem``) or about when a
number is issued (that is the repository's ``register``). It only:

* turns caller input into a :class:`~compound_registry.models.Normalized`,
  applying the configured default stereo mode (see :meth:`RegistryService._normalize`);
* reports what the registry knows (``analyze``, ``find_by_id``, ``compounds``)
  in a stable dict shape, with display-only values (``properties``, see
  :mod:`compound_registry.properties`) and the stored names;
* stores the name of a stereo variant, typed by the user (``set_name``) or
  generated by the local ChemDraw (``generate_name``, see
  :mod:`compound_registry.naming`): an annotation, not an ID, so it is not
  behind the two guards below;
* stores the yields of a batch mirrored from the ELN (``set_yield``) and
  lists them (``yields``): an annotation like a name;
* makes the compound's folder on this PC when an ID is created and serves
  what is in it (``compound_files``, ``read_pdf``, ``make_folders``; the
  file-system side is :mod:`compound_registry.files`);
* stores the reaction of an experiment mirrored from the ELN
  (``set_reaction``, ``reaction``) and the starting material the user chose
  for it (``set_limiting``): annotations like a yield; and draws
  the synthesis route of a stereo variant from the stored reactions as a
  ChemDraw file in the compound's folder (``route``; the route itself is
  :mod:`compound_registry.routes`, the drawing :mod:`compound_registry.cdxml`);
* runs the automatic backup after every write and reports its outcome;
* offers maintenance views (``rekey_check``, ``doctor``).

Two guards protect the meaning of issued IDs:

* **Stale database** - every new ID and retirement is also appended to the
  issued-ID journal (see :mod:`compound_registry.journal`), outside the
  database. Before the first write of a service instance, the journal is
  compared with the database; if the database lacks journalled IDs (it was
  probably restored from an older backup) every write is refused with
  ``database_older_than_journal`` until :meth:`RegistryService.recover` has
  re-created them. Batches the journal lacks are appended to it ("catch-up").
  Journal lines written by ANOTHER registry (two registries pointed at one
  backup folder, or two databases in one home folder) are never taken for
  lost IDs: every write is refused with ``journal_shared`` until each
  registry has a folder of its own. Lines that name no registry are only
  the lines of a registry whose own journal began that way; it gives them
  its name at the catch-up (see :mod:`compound_registry.journal`).
* **Chemistry version** - the RDKit / InChI / key-recipe fingerprint is stored
  in the database meta table. If it changes, ``register`` is refused with
  ``chemistry_version_changed`` until ``rekey_check(accept=True)`` confirmed
  that every stored structure still gives the same keys. An upgrade of the
  program runs that check by itself (:func:`upgrade_registry`).

The command line and the installer create a registry with
:func:`create_registry`.
"""

