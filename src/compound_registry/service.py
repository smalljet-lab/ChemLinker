def create_registry(home: Path | str | None = None,
                    id_format: str | None = None) -> tuple[Config, list[str]]:
    """Create a NEW registry in ``home`` (None: ``$COMPOUND_REGISTRY_HOME`` /
    the default folder). The command line ('init') and the installer both
    create a registry here.

    ``id_format``: the ID template of the new registry (None: the format of
    an existing ``config.toml``, else the default). It is permanent, so it is
    checked first (:meth:`IdFormat.require_file_safe`).

    * Neither ``config.toml`` nor the database exists: ``config.toml`` is
      written (with ``id_format``) and the database is created.
    * Only ``config.toml`` exists (prepared by hand): the database it names
      is created.
    * Only the database exists (its ``config.toml`` was lost): a default
      ``config.toml`` is written and the database is opened with it; a
      database with another ID format refuses that, and the file is removed
      again.
    * Both exist: nothing is created (``registry_exists``).
    * With ``id_format``, anything that exists is refused
      (``invalid_argument``): the format of an existing registry cannot be
      changed, and an existing ``config.toml`` already names one.

    If the database cannot be created, a ``config.toml`` written by this call
    is removed again.

    When the folder already holds an issued-ID journal (the database was
    lost, the journal survived), the new database continues the registry of
    that journal (see :meth:`RegistryService._journal_survivor`), and a
    warning says to run ``recover`` first.

    Returns ``(config, warnings)``; the warnings also say when the database
    lies in a cloud-sync folder or on a network drive
    (:func:`compound_registry.config.sync_folder_warning`). Raises
    ``ConfigError`` for an unusable format, folder or ``config.toml``.
    """
    config = load_config(Path(home) if home is not None else None, create=False)
    config_path = Path(config.config_path)
    has_config = config_path.is_file()
    has_database = Path(config.db_path).is_file()
    if id_format is not None:
        IdFormat(id_format).require_file_safe()
        if has_config or has_database:
            raise RegistryError(
                f"An ID format can only be chosen for a new registry, but {config.home} "
                "already has one (or a config.toml). The ID format of an existing registry "
                "cannot be changed.", code="invalid_argument")
    elif has_config and has_database:
        raise RegistryError(
            f"A registry already exists in {config.home} ({config.db_path}); nothing "
            "was created.", code="registry_exists")
    elif not has_database:
        IdFormat(config.id_format).require_file_safe()
    warnings: list[str] = []
    synced = sync_folder_warning(config.db_path)
    if synced:
        warnings.append(synced)
    journal = Path(config.home) / journal_mod.JOURNAL_FILENAME
    try:
        journal_used = journal.is_file() and journal.stat().st_size > 0
    except OSError:
        journal_used = False
    if journal_used and not has_database:
        warnings.append(f"An issued-ID journal exists in {config.home} ({journal}): IDs "
                        "were issued from this folder before. Run 'compound-registry "
                        "recover' before registering anything.")
    wrote_config = False
    if not has_config:
        try:
            Path(config.home).mkdir(parents=True, exist_ok=True)
        except OSError as exc:
            reason = ("a file with this name, or with the name of a folder above it, is in "
                      "the way" if isinstance(exc, (FileExistsError, NotADirectoryError))
                      else str(exc))
            raise RegistryError(f"The folder {config.home} cannot be created: {reason}. "
                                "Nothing was created.", code="config_invalid") from None
        try:
            with open(config_path, "x", encoding="utf-8", newline="\n") as fh:
                fh.write(config_text(id_format))
            wrote_config = True
        except FileExistsError:
            raise RegistryError(
                f"{config_path} was created by another program at the same moment; nothing "
                "was created. Try again.", code="registry_exists") from None
        except OSError as exc:
            raise RegistryError(f"Cannot create {config_path}: {exc}",
                                code="config_invalid") from None
    try:
        config = load_config(Path(config.home), create=False)
        RegistryService(config).close()
    except BaseException:
        if wrote_config:
            try:
                os.remove(config_path)
            except OSError:
                pass
        try:
            if not has_database and Path(config.db_path).stat().st_size == 0:
                os.remove(config.db_path)
        except OSError:
            pass
        raise
    return config, warnings


def upgrade_registry(home: Path | str | None = None) -> dict[str, Any]:
    """What an installation over an older program version does to the
    registry in ``home``, without asking anything and without ever creating
    a registry:

    * opening it brings the database file up to date (a schema upgrade with
      a copy made first, missing annotation tables, the ``registry_id``);
    * the issued-ID journal is brought up to date, so that every line of
      this registry names it (:meth:`RegistryService.stamp_journal`);
    * :meth:`RegistryService.chemistry_upgrade` checks every stored structure
      when the chemistry version changed, and accepts the new version when
      all keys are unchanged.

    Returns ``{"status", "message", "home", ...}``. ``status`` is
    ``"no_registry"`` (nothing exists in ``home``; nothing was done), else
    the status of :meth:`RegistryService.chemistry_upgrade` (``"current"``,
    ``"accepted"`` or ``"blocked"``) with its keys plus ``registry_id``,
    ``schema_version``, ``program_version`` and ``schema_upgrade``
    (``{"from", "to", "backup"}`` or None). Raises ``RegistryError`` when the
    registry cannot be opened.
    """
    config = load_config(Path(home) if home is not None else None, create=False)
    if not Path(config.config_path).is_file() or not Path(config.db_path).is_file():
        return {"status": "no_registry", "home": str(config.home),
                "message": f"No registry exists in {config.home}; nothing was checked."}
    with RegistryService(config) as svc:
        if not getattr(svc.repo, "read_only", False):
            svc.stamp_journal()
        result = svc.chemistry_upgrade()
        upgrade = getattr(svc.repo, "upgrade", None)
        result.update({
            "home": str(config.home),
            "registry_id": svc._registry_id(),
            "schema_version": getattr(svc.repo, "schema_version", None),
            "program_version": __version__,
            "schema_upgrade": dict(upgrade) if upgrade else None,
        })
    if upgrade:
        result["message"] = (f"The database was upgraded from schema {upgrade['from']} to "
                             f"{upgrade['to']} (copy of the old file: {upgrade['backup']}). "
                             + result["message"])
    return result
