    def _reaction_store(self, name: str) -> Callable[..., Any]:
        fn = getattr(self.repo, name, None)
        if fn is None:
            raise RegistryError("This storage backend cannot store reactions.",
                                code="not_supported")
        return fn

    def set_reaction(self, experiment_ref: str, reaction: Any, experiment_code: str | None = None,
                     experiment_url: str | None = None) -> dict[str, Any]:
        """Store what the page of an experiment shows about its reaction,
        replacing what was stored for it; returns ``{"experiment_ref",
        "changed", "updated_at", "warnings"}`` (see protocol.py,
        "Reactions"). ``changed`` is false when exactly this was stored
        already (then nothing is written).

        ``reaction`` is checked and completed like the host checks it (see
        :func:`clean_reaction`; ``invalid_argument`` otherwise). Only the
        reactions of experiments that produced a registered compound are
        stored: ``NotFoundError`` unless at least one batch (active or
        retired) was registered for ``experiment_ref``. Without
        ``experiment_code`` / ``experiment_url`` the ones recorded with those
        batches are kept with the reaction.

        Like :meth:`set_yield`: written even while the guards block
        registering, not written to the issued-ID journal, recorded in the
        event log (``reaction_set``), followed by the automatic backup after
        a change.
        """
        ref = self._experiment_ref(experiment_ref, required=True)
        code = self._optional_text("experiment_code", experiment_code)
        url = self._optional_text("experiment_url", experiment_url)
        if url is not None and not protocol.is_safe_url(url):
            raise _invalid("experiment_url must be an absolute http(s) address.")
        data = clean_reaction(reaction)
        setter = self._reaction_store("set_reaction")
        batches = self.repo.find_batches(ref)
        if not batches:
            named = f" ({code})" if code else ""
            raise NotFoundError(
                f"No compound of the registry was made in the experiment with internal key "
                f"{ref}{named}. Only the reactions of experiments with a registered product "
                "are stored; nothing was stored.")
        if code is None:
            code = next((b.experiment_code for b in reversed(batches) if b.experiment_code), None)
        if url is None:
            url = next((b.experiment_url for b in reversed(batches) if b.experiment_url), None)
        record, changed = setter(ref, code, url, data)
        warnings = self._service_warnings()
        if changed:
            backup = self._backup_after_write()
            if backup["warning"]:
                warnings.append(backup["warning"])
        return {"experiment_ref": ref, "changed": bool(changed),
                "updated_at": record["updated_at"], "warnings": warnings}

    def set_limiting(self, experiment_ref: str, row: int | None) -> dict[str, Any]:
        """Choose the starting material ("SM" on the run line of a route) of
        an experiment whose reaction is stored: the reactant in ``row`` (its
        ``row`` number in the stored reaction), or None to go back to the
        automatic choice. Returns ``{"experiment_ref", "row", "name",
        "changed", "warnings"}`` (see protocol.py, "Synthesis routes");
        ``name`` is that reactant's name at this moment (else its formula,
        else null; null for automatic) and is recorded with the choice, so a
        route can tell when the reaction no longer has that reactant.

        ``NotFoundError`` when no reaction is stored for ``experiment_ref``
        (the internal key); ``invalid_argument`` when the stored reaction has
        no reactant in ``row``. The choice is kept beside the reaction and
        survives every later :meth:`set_reaction`. Like :meth:`set_reaction`:
        written even while the guards block registering, not written to the
        issued-ID journal, recorded in the event log (``limiting_set``),
        followed by the automatic backup after a change.
        """
        ref = self._experiment_ref(experiment_ref, required=True)
        if row is not None and (isinstance(row, bool) or not isinstance(row, int)
                                or not 1 <= row <= protocol.MAX_PRODUCT_INDEX):
            raise _invalid(f"The reactant row must be a whole number from 1 to "
                           f"{protocol.MAX_PRODUCT_INDEX}, or null for automatic; got {row!r}.")
        getter = self._reaction_store("get_reaction")
        setter = getattr(self.repo, "set_limiting", None)
        if setter is None:
            raise RegistryError("This storage backend cannot store the starting material of "
                                "an experiment.", code="not_supported")
        record = getter(ref)
        if record is None:
            raise NotFoundError(
                f"No reaction is stored for the experiment with internal key {ref}. Showing "
                "the experiment once in the ELN with the extension stores it.")
        name: str | None = None
        if row is not None:
            data = record.get("data")
            reactants = data.get("reactants") if isinstance(data, dict) else None
            reactants = reactants if isinstance(reactants, list) else []
            component = next((c for i, c in enumerate(reactants)
                              if isinstance(c, dict) and _reactant_row(c, i) == row), None)
            if component is None:
                where = record.get("experiment_code") or ref
                rows = sorted(_reactant_row(c, i) for i, c in enumerate(reactants)
                              if isinstance(c, dict))
                listed = (f"its reactant rows are {', '.join(str(r) for r in rows)}" if rows
                          else "it has no reactants")
                raise _invalid(f"The stored reaction of {where} has no reactant in row {row} "
                               f"({listed}); nothing was changed.")
            name = _reactant_name(component)
        changed = setter(ref, row, name)
        warnings = self._service_warnings()
        if changed:
            backup = self._backup_after_write()
            if backup["warning"]:
                warnings.append(backup["warning"])
        return {"experiment_ref": ref, "row": row, "name": name, "changed": bool(changed),
                "warnings": warnings}

    def _experiment_refs_of_code(self, code: str) -> list[str]:
        """Internal keys of the experiments with this ELN number (ignoring
        case), from the batches and the stored reactions."""
        wanted = code.casefold()
        refs: list[str] = []
        summaries = getattr(self.repo, "batch_summaries", None)
        rows = (summaries() if summaries is not None else
                [dataclasses.asdict(b) for b in self.repo.iter_batches(include_retired=True)])
        refs.extend(r["experiment_ref"] for r in rows
                    if isinstance(r.get("experiment_code"), str)
                    and r["experiment_code"].strip().casefold() == wanted)
        lister = getattr(self.repo, "list_reactions", None)
        if lister is not None:
            refs.extend(r["experiment_ref"] for r in lister()
                        if isinstance(r.get("experiment_code"), str)
                        and r["experiment_code"].strip().casefold() == wanted)
        return list(dict.fromkeys(refs))

    def reaction(self, experiment: str) -> dict[str, Any]:
        """Read-only: the reaction stored for an experiment, given by its
        internal key or else by its ELN number (ignoring case): ``{"experiment_ref",
        "experiment_code", "experiment_url", "updated_at", "reaction"}``.
        ``NotFoundError`` when none is stored."""
        text = self._experiment_ref(experiment, required=True)
        getter = self._reaction_store("get_reaction")
        record = getter(text)
        if record is None:
            for ref in self._experiment_refs_of_code(text):
                record = getter(ref)
                if record is not None:
                    break
        if record is None:
            raise NotFoundError(
                f"No reaction is stored for the experiment {text!r} (an internal key or an ELN "
                "number). Showing the experiment once in the ELN with the extension stores it.")
        return {"experiment_ref": record["experiment_ref"],
                "experiment_code": record["experiment_code"],
                "experiment_url": record["experiment_url"],
                "updated_at": record["updated_at"], "reaction": record["data"]}

