    #: Room left in MAX_RESPONSE_BYTES for the response envelope (id, ok).
    _RESPONSE_MARGIN = 2_000

    @staticmethod
    def _core_stereo_arg(core_stereo_id: object) -> str:
        if not isinstance(core_stereo_id, str) or not core_stereo_id.strip():
            raise _invalid("A CORE_STEREO ID is required.")
        return core_stereo_id.strip()

    def _stereo_molfile(self, core_stereo_id: str) -> str | None:
        """The stored molfile of a stereo variant ('' when none is stored),
        or None when no such stereo variant is registered."""
        fn = getattr(self.repo, "get_stereo", None)
        if fn is not None:
            record = fn(core_stereo_id)
            return None if record is None else (record.molfile or "")
        for b in self.repo.iter_batches(include_retired=True):  # batch 1 comes first
            if b.core_stereo_id == core_stereo_id:
                return b.molfile or ""
        return None

    def _all_stereo_molfiles(self) -> list[tuple[str, str]]:
        """``(CORE_STEREO, molfile)`` of every registered stereo variant."""
        lister = getattr(self.repo, "list_stereos", None)
        if lister is not None:
            return [(s.core_stereo_id, s.molfile or "") for s in lister()]
        seen: dict[str, str] = {}
        for b in self.repo.iter_batches(include_retired=True):
            seen.setdefault(b.core_stereo_id, b.molfile or "")
        return list(seen.items())

    def _ensure_folder(self, core_stereo_id: str, molfile: str | None = None,
                       fallback_molfile: str | None = None) -> tuple[dict[str, Any] | None,
                                                                     str | None]:
        """``({"path", "created"} or None, warning or None)`` after making
        sure the folder of a stereo variant exists. Never raises."""
        try:
            if molfile is None:
                try:
                    molfile = self._stereo_molfile(core_stereo_id)
                except RegistryError:
                    molfile = None
                if molfile is None:
                    molfile = fallback_molfile
            outcome = files_mod.ensure_folder(self.config.files_dir, core_stereo_id, molfile)
        except Exception as exc:  # noqa: BLE001 - a folder problem never fails a registration
            return None, (f"The folder of {core_stereo_id} could not be made: "
                          f"{type(exc).__name__}: {exc}")
        if outcome.path is None:
            return None, outcome.warning
        return {"path": str(outcome.path), "created": bool(outcome.created)}, outcome.warning

    def make_folders(self, core_stereo_id: str | None = None) -> dict[str, Any]:
        """Make the missing folder of one stereo variant (``core_stereo_id``)
        or of every registered one, with its ``<CORE_STEREO>.mol``; nothing
        that exists is changed. Returns ``{"files_folder", "folders":
        [{"core_stereo_id", "path", "created", "warning"}], "created",
        "failed"}``: ``path`` None when no folder could be made (``warning``
        says why); ``created`` false with a path means it was already there.
        ``NotFoundError`` for an unknown ``core_stereo_id``."""
        if core_stereo_id is not None:
            cs = self._core_stereo_arg(core_stereo_id)
            molfile = self._stereo_molfile(cs)
            if molfile is None:
                raise NotFoundError(f"No stereo variant {cs!r} is registered.")
            variants = [(cs, molfile)]
        else:
            variants = self._all_stereo_molfiles()
        entries = []
        for cs, molfile in variants:
            folder, warning = self._ensure_folder(cs, molfile=molfile)
            entries.append({"core_stereo_id": cs,
                            "path": folder["path"] if folder is not None else None,
                            "created": bool(folder is not None and folder["created"]),
                            "warning": warning})
        return {"files_folder": str(self.config.files_dir), "folders": entries,
                "created": sum(1 for e in entries if e["created"]),
                "failed": sum(1 for e in entries if e["path"] is None)}

    @staticmethod
    def _spectrum_item(record: dict[str, Any], experiment_code: str | None,
                       pdf_path: Path | None = None) -> dict[str, Any]:
        """One recorded spectrum as ``compound_files`` sends it (never the
        HTML report). ``pdf_path`` is where its PDF is now (see
        :func:`compound_registry.files.resolve_recorded`)."""
        data = record.get("data") if isinstance(record.get("data"), dict) else {}

        def text(name: str) -> str | None:
            value = data.get(name)
            return value if isinstance(value, str) and value.strip() else None

        report = text("report")
        report = " ".join(report.split()) if report is not None else None
        frequency = data.get("frequency_mhz")
        if isinstance(frequency, bool) or not isinstance(frequency, (int, float)) \
                or frequency != frequency or frequency in (float("inf"), float("-inf")):
            frequency = None
        dimensions = data.get("dimensions")
        if isinstance(dimensions, bool) or not isinstance(dimensions, int):
            dimensions = None
        raw_parameters = data.get("parameters")
        parameters = []
        if isinstance(raw_parameters, dict):
            parameters = [{"name": str(k), "value": str(v)}
                          for k, v in raw_parameters.items() if v is not None]
            parameters.sort(key=lambda p: (p["name"].casefold(), p["name"]))
        pdf_file = text("pdf_file")
        return {
            "full_id": record.get("full_id"),
            "spectrum_key": record.get("spectrum_key"),
            "updated_at": record.get("updated_at"),
            "experiment_code": experiment_code,
            "title": text("title"),
            "comment": text("comment"),
            "sample": text("sample"),
            "nucleus": text("nucleus"),
            "solvent": text("solvent"),
            "experiment": text("experiment"),
            "pulse_sequence": text("pulse_sequence"),
            "frequency_mhz": frequency,
            "dimensions": dimensions,
            "report": report or None,
            "parameters": parameters,
            "mnova_file": text("mnova_file"),
            "pdf_file": pdf_file,
            "pdf_available": pdf_path is not None and files_mod.pdf_readable(str(pdf_path)),
        }

    def _compound_spectra(self, core_stereo_id: str) -> list[dict[str, Any]]:
        reader = getattr(self.repo, "get_spectra", None)
        if reader is None:
            return []
        records = sorted(reader(core_stereo_id=core_stereo_id),
                         key=lambda r: (str(r.get("full_id")), str(r.get("spectrum_key"))))
        codes: dict[str, str | None] = {}
        for full_id in dict.fromkeys(r.get("full_id") for r in records):
            batch = self.repo.get_batch(full_id) if isinstance(full_id, str) else None
            codes[full_id] = batch.experiment_code if batch is not None else None
        return [self._spectrum_item(r, codes.get(r.get("full_id")),
                                    self._recorded_path(core_stereo_id, r, "pdf_file"))
                for r in records]

    def _recorded_path(self, core_stereo_id: str, record: dict[str, Any],
                       field: str) -> Path | None:
        """Where the file a spectrum record names in ``field`` is now."""
        data = record.get("data") if isinstance(record.get("data"), dict) else {}
        return files_mod.resolve_recorded(self.config.files_dir, core_stereo_id, data.get(field))

    @classmethod
    def _fit_compound_files(cls, result: dict[str, Any]) -> None:
        """Drop the ``parameters`` of spectra, from the end, until the answer
        fits the host's response limit (with a warning)."""
        limit = protocol.MAX_RESPONSE_BYTES - cls._RESPONSE_MARGIN

        def size() -> int:
            return len(json.dumps(result, ensure_ascii=False, separators=(",", ":"))
                       .encode("utf-8"))

        if size() <= limit:
            return
        dropped = 0
        warning: str | None = None
        for item in reversed(result["spectra"]):
            if not item["parameters"]:
                continue
            item["parameters"] = []
            dropped += 1
            if warning is not None:
                result["warnings"].remove(warning)
            warning = (f"The acquisition parameters of {dropped} "
                       f"{'spectrum were' if dropped == 1 else 'spectra were'} left out because "
                       "the answer was too large to send to the browser.")
            result["warnings"].append(warning)
            if size() <= limit:
                return

    def compound_files(self, core_stereo_id: str) -> dict[str, Any]:
        """Read-only: the folder of a stereo variant on this PC, the spectra
        recorded for its batches and the files in the folder: ``{"core_stereo_id",
        "folder", "spectra", "files", "files_truncated", "warnings"}`` as
        protocol.py, "Compound folders and spectra", describes. The folder is
        not made here. ``NotFoundError`` for an unknown stereo variant."""
        cs = self._core_stereo_arg(core_stereo_id)
        if self._stereo_molfile(cs) is None:
            raise NotFoundError(f"No stereo variant {cs!r} is registered.")
        warnings: list[str] = []
        spectra = self._compound_spectra(cs)
        recorded = [p for s in spectra for p in
                    (files_mod.resolve_recorded(self.config.files_dir, cs, s[field])
                     for field in ("mnova_file", "pdf_file"))
                    if p is not None]
        files: list[dict[str, Any]] = []
        truncated = False
        folder_path = files_mod.compound_folder(self.config.files_dir, cs)
        if folder_path is None:
            folder = None
            warnings.append(f"{cs} cannot be used as a folder name, so this compound has no "
                            "folder on this PC.")
        else:
            exists = folder_path.is_dir()
            folder = {"path": str(folder_path), "exists": exists}
            if exists:
                files, truncated, warning = files_mod.list_files(folder_path)
                if warning:
                    warnings.append(warning)
                for f in files:
                    f["recorded"] = any(files_mod.same_path(folder_path / f["name"], p)
                                        for p in recorded)
        result = {"core_stereo_id": cs, "folder": folder, "spectra": spectra, "files": files,
                  "files_truncated": truncated, "warnings": warnings}
        self._fit_compound_files(result)
        return result

    def read_pdf(self, core_stereo_id: str, name: str | None = None, full_id: str | None = None,
                 spectrum_key: str | None = None, offset: int = 0) -> dict[str, Any]:
        """Read-only: one piece of a PDF of a stereo variant, ``{"name",
        "size", "offset", "data", "eof"}`` (see
        :func:`compound_registry.files.read_pdf_chunk`). Either ``name``, a
        PDF lying directly in the compound's folder, or ``full_id`` with
        ``spectrum_key``, the ``pdf_file`` recorded for that spectrum of a
        batch of this stereo variant. A recorded PDF that is no longer at its
        recorded path is read from the compound's folder when a file of the
        same name lies there (the files folder was moved).

        ``not_found``: unknown stereo variant, a batch of another variant, a
        spectrum that is not recorded. ``file_unavailable``: no PDF recorded
        for the spectrum, a recorded path that leads nowhere, no such
        file, not a PDF, too large, outside the folder. ``invalid_argument``:
        a ``name`` that is not a plain file name, a bad ``offset``."""
        cs = self._core_stereo_arg(core_stereo_id)
        if isinstance(offset, bool) or not isinstance(offset, int) or offset < 0:
            raise _invalid(f"offset must be a whole number >= 0, got {offset!r}.")
        by_name = name is not None
        if by_name == (full_id is not None or spectrum_key is not None) \
                or (not by_name and (full_id is None or spectrum_key is None)):
            raise _invalid("Give either the name of a PDF in the compound's folder, or a full "
                           "ID together with a spectrum key.")
        if self._stereo_molfile(cs) is None:
            raise NotFoundError(f"No stereo variant {cs!r} is registered.")
        if by_name:
            folder = files_mod.compound_folder(self.config.files_dir, cs)
            if folder is None:
                raise RegistryError(f"{cs} cannot be used as a folder name, so this compound "
                                    "has no folder on this PC.", code="file_unavailable")
            path = files_mod.resolve_pdf_name(folder, name)
        else:
            if not isinstance(full_id, str) or not full_id.strip() \
                    or not isinstance(spectrum_key, str) or not spectrum_key.strip():
                raise _invalid("A full ID and a spectrum key are required.")
            fid, key = full_id.strip(), spectrum_key.strip()
            batch = self.repo.get_batch(fid)
            if batch is None or batch.core_stereo_id != cs:
                raise NotFoundError(f"{fid} is not a registered batch of {cs}.")
            reader = getattr(self.repo, "get_spectra", None)
            records = reader(full_id=fid) if reader is not None else []
            record = next((r for r in records if r.get("spectrum_key") == key), None)
            if record is None:
                raise NotFoundError(f"No spectrum {key!r} is recorded for {fid}.")
            data = record.get("data") if isinstance(record.get("data"), dict) else {}
            pdf = data.get("pdf_file")
            if not isinstance(pdf, str) or not pdf.strip():
                raise RegistryError(f"No PDF is recorded for the spectrum {key!r} of {fid}.",
                                    code="file_unavailable")
            path = files_mod.resolve_recorded(self.config.files_dir, cs, pdf)
            if path is None:
                raise RegistryError(f"The PDF recorded for the spectrum {key!r} of {fid} ({pdf}) "
                                    "cannot be found: it is not a full path and not a file "
                                    "name in the compound's folder.", code="file_unavailable")
        return files_mod.read_pdf_chunk(path, offset)

