class RegistryService:
    """Facade over chemistry, storage and backup. Use as a context manager or
    call :meth:`close` when done."""

    def __init__(self, config: Config, repo: RegistryRepository | None = None, *,
                 name_asker: Callable[[str], Any] | None = None,
                 opener: Callable[[str], Any] | None = None,
                 local_clock: Callable[[], datetime] | None = None):
        self.config = config
        # Hands a molfile to the naming program for generate_name (see
        # naming.generate's ``ask``); None means the installed ChemDraw.
        self.name_asker = name_asker
        # Opens a file written by ``route`` (its path as text); None means
        # "ask the system": on Windows outside the host's Job object
        # (open_outside_job), on macOS with ``open`` (open_with_system).
        # ``local_clock`` gives the local time
        # used in the file name; None means now.
        self.opener = opener
        self.local_clock = local_clock
        self._db_existed_at_open = Path(config.db_path).is_file()
        self.journal = Journal.for_config(config)
        # Journal compared with the database and caught up (once per instance;
        # reset when an append fails or after recover).
        self._journal_verified = False
        self._journal_check_cache: _JournalCheck | None = None
        self._chemistry_cache: dict[str, Any] | None = None
        if repo is None:
            # A database that is created here in a home folder whose journal
            # survived continues the registry of that journal.
            survivor, unstamped_own = ((None, False) if self._db_existed_at_open
                                       else self._journal_survivor(config))
            repo = open_repository(config, survivor, unstamped_own)
        self.repo: RegistryRepository = repo
        if getattr(repo, "identity_added", False):
            # The file just got its registry_id: let its journal name it too.
            self.stamp_journal()

    @classmethod
    def open(cls, home: Path | None = None) -> "RegistryService":
        """Load ``<home>/config.toml`` (created with defaults if missing) and
        open the registry it describes."""
        return cls(load_config(home))

    # ------------------------------------------------------------------ lifecycle
    def close(self) -> None:
        """Close the repository. Safe to call more than once."""
        repo = getattr(self, "repo", None)
        if repo is not None:
            repo.close()

    def __enter__(self) -> "RegistryService":
        return self

    def __exit__(self, *exc_info: object) -> None:
        self.close()

    # ------------------------------------------------------------------ helpers
    def _service_warnings(self) -> list[str]:
        warning = sync_folder_warning(Path(self.config.db_path))
        return [warning] if warning else []

    def _read_warnings(self) -> list[str]:
        """Warnings for read-only views: sync folder, stale database, chemistry change."""
        warnings = self._service_warnings()
        try:
            check = self._journal_check()
        except RegistryError as exc:
            warnings.append(f"The issued-ID journal could not be checked: {exc.message}")
        else:
            warnings.extend(self._journal_problem_texts(check))
        chem_state = self._chemistry_state()
        if chem_state["changed"]:
            warnings.append(self._chemistry_message(chem_state, blocked=False))
        return warnings

    # ------------------------------------------------------------------ journal guard
    @staticmethod
    def _journal_survivor(config: Config) -> tuple[str | None, bool]:
        """For a database that is about to be created: ``(the identity it
        continues or None, whether the journal lines that name no registry
        are its own)``, from the main journal of its home folder.

        Lines that name a registry give the identity. A journal whose lines
        name none belongs to a registry whose identity is in its backups
        only: the newest backup that holds nothing but registrations of that
        journal gives it, so that those backups stay this registry's."""
        origin = journal_mod.journal_origin(config)
        if origin.registry_id or not origin.unstamped:
            return origin.registry_id, bool(origin.unstamped)
        registrations = {
            line["id"]: tuple(line.get(name) for name in journal_mod.IDENTITY_FIELDS)
            for line in origin.unstamped if line["event"] == "register"}
        return backup_mod.registry_id_from_backups(config, registrations), True

    def _journal_check(self, fresh: bool = False) -> _JournalCheck:
        """Compare the journal(s) with the database (cached per instance)."""
        if self._journal_check_cache is not None and not fresh:
            return self._journal_check_cache
        files = self.journal.read(self._registry_id(),
                                  bool(getattr(self.repo, "unstamped_journal_own", True)))
        entries = journal_mod.merge(files)
        in_db = {b.full_id: b for b in self.repo.iter_batches(include_retired=True)}
        check = _JournalCheck(files=files, entries=entries)
        for entry in entries:
            batch = in_db.get(entry["id"])
            if entry["event"] == "register":
                if batch is None:
                    check.missing_register.append(entry["id"])
                elif any(entry.get(name) != self._batch_identity(batch)[name]
                         for name in journal_mod.IDENTITY_FIELDS):
                    check.conflicts.append(entry["id"])
                else:
                    check.already_present += 1
            else:  # retire
                # (If the database does not know the ID at all, recover needs
                # its journalled registration; without one, recover refuses.)
                if batch is None or not batch.retired:
                    check.missing_retire.append(entry["id"])
                else:
                    check.already_present += 1
        self._journal_check_cache = check
        return check

    def _registry_id(self) -> str | None:
        """The identity of the open registry (None for a storage backend
        without one)."""
        return getattr(self.repo, "registry_id", None) or None

    @staticmethod
    def _batch_identity(batch: BatchRecord) -> dict[str, Any]:
        return {"at": batch.created_at, "experiment_ref": batch.experiment_ref,
                "product_index": batch.product_index, "inchikey": batch.inchikey}

    def _journal_problem_texts(self, check: _JournalCheck) -> list[str]:
        texts: list[str] = []
        if check.shared:
            texts.append(self._shared_message(check))
        if check.conflicts:
            texts.append(self._conflict_message(check))
        if check.stale:
            texts.append(self._stale_message(check))
        for jf in check.files:
            if jf.error:
                texts.append(f"Issued-ID journal: {jf.error}")
            if jf.unreadable_lines:
                texts.append(f"Issued-ID journal {jf.path}: {jf.unreadable_lines} unreadable "
                             "line(s) were ignored (e.g. a write cut short by a crash).")
        return texts

    def _stale_message(self, check: _JournalCheck) -> str:
        parts = []
        if check.missing_register:
            parts.append(f"{len(check.missing_register)} issued ID(s) ({_name_ids(check.missing_register)})")
        if check.missing_retire:
            parts.append(f"{len(check.missing_retire)} retirement(s) "
                         f"({_name_ids(check.missing_retire)})")
        return (
            f"The registry database {self.config.db_path} is missing {' and '.join(parts)} "
            f"recorded in the issued-ID journal ({self.journal.path}). The database was "
            "probably restored from an older backup. Issuing new IDs now could hand out IDs "
            "that already exist in your notebook, so registering and retiring are blocked. "
            "Run 'compound-registry recover' to re-create the missing entries from the journal."
        )

    def _shared_message(self, check: _JournalCheck) -> str:
        """Why a journal file with lines of another registry blocks writing,
        and what to do (never 'recover': those IDs are not this registry's)."""
        unnamed = journal_mod.UNNAMED_REGISTRY
        others = ", ".join(
            [rid for rid in check.other_registries if rid != unnamed]
            + (["one made by an older program version, whose journal lines name no registry"]
               if unnamed in check.other_registries else []))
        parts = []
        for jf in check.shared:
            lines = sum(jf.foreign.values())
            if self.journal.mirror_path is not None and jf.path == self.journal.mirror_path:
                parts.append(
                    f"The backup folder {self.config.backup_dir} is used by another registry: "
                    f"its issued-ID journal {jf.path} holds {lines} line(s) of that registry. "
                    "Give each registry its own backup folder: set [backup] folder in "
                    f"{self.config.config_path} to a folder that only this registry uses. "
                    "(If that folder is this registry's and its database was lost and made "
                    "anew, restore the latest backup instead: 'compound-registry backup "
                    "--list'.)")
            else:
                parts.append(
                    f"The issued-ID journal {jf.path} holds {lines} line(s) of another "
                    f"registry, so the folder {self.config.home} is used by two registries. "
                    "Give each registry its own home folder: move this database, with a "
                    "config.toml of its own, to a folder that only this registry uses.")
        return (" ".join(parts) + f" (This registry is {self._registry_id()}; the other: "
                f"{others}.) Until then registering and retiring are blocked, because the two "
                "registries would mix up their IDs and their backups. Do not run "
                "'compound-registry recover' for this: nothing is missing from this database.")

    def _conflict_message(self, check: _JournalCheck) -> str:
        return (
            f"{len(check.conflicts)} ID(s) in the issued-ID journal ({self.journal.path}) "
            f"describe something different from the database ({_name_ids(check.conflicts)}): "
            "the same ID seems to have been issued twice or the database was edited. Writes "
            "are blocked; compare the journal with the database and with the lab notebook "
            "before doing anything else."
        )

    def _before_write(self) -> None:
        """Refuse to write to a database that is older than the journal, then
        append to the journal whatever the database has and it lacks."""
        if self._journal_verified:
            return
        check = self._journal_check(fresh=True)
        if check.shared:
            raise RegistryError(self._shared_message(check), code="journal_shared")
        if check.conflicts:
            raise RegistryError(self._conflict_message(check), code="journal_conflict")
        if check.stale:
            raise RegistryError(self._stale_message(check), code="database_older_than_journal")
        main = check.files[0]
        if main.error:
            raise RegistryError(
                f"The issued-ID journal cannot be read ({main.error}), so it cannot be checked "
                "that the database is up to date. Nothing was written.",
                code="journal_unreadable",
            )
        self._journal_verified = self._catch_up(check)

    def stamp_journal(self) -> bool:
        """Bring the journal files up to date with the database now instead
        of at the next write (see :meth:`_catch_up`), so that every line of
        this registry names it. Nothing is done, and False returned, while
        writing is blocked (journal of another registry, conflict, database
        older than the journal, unreadable journal)."""
        try:
            self._before_write()
        except RegistryError:
            return False
        return self._journal_verified

    def _catch_up(self, check: _JournalCheck) -> bool:
        """Append to each journal file the registrations / retirements the
        database holds but that file lacks (oldest first), and a copy with
        this registry's ``registry_id`` of each of its lines that names no
        registry. Returns False when the main journal could not be written
        (to be tried again at the next write). Needs the repository's
        ``registration_details``; other backends skip this."""
        details_fn = getattr(self.repo, "registration_details", None)
        if details_fn is None:
            return True
        wanted: list[tuple[int, tuple[str, str], dict[str, Any]]] = []
        registry_id = self._registry_id()
        for d in details_fn():
            entry = journal_mod.register_entry(
                d["id"], d["at"], experiment_ref=d["experiment_ref"],
                experiment_code=d["experiment_code"], experiment_url=d["experiment_url"],
                product_index=d["product_index"], source=d["source"], norm=d,
                registry_id=registry_id)
            wanted.append((d.get("register_seq") or 0, ("register", d["id"]), entry))
            if d["retired_at"] is not None:
                wanted.append((d.get("retire_seq") or 0, ("retire", d["id"]),
                               journal_mod.retire_entry(d["id"], d["retired_at"],
                                                        d["retired_reason"], registry_id)))
        wanted.sort(key=lambda item: item[0])  # stable: event-log order
        per_file = [
            ([journal_mod.stamped(line, registry_id) for line in jf.unstamped]
             if registry_id else [])
            + [e for _, key, e in wanted if key not in jf.keys()]
            for jf in check.files]
        main_missing = per_file[0]
        mirror_missing = per_file[1] if len(per_file) > 1 else []
        main_ok = all_written = True
        if main_missing or mirror_missing:
            outcome = self.journal.append(main_missing, mirror_entries=mirror_missing)
            # A main journal that could not be written is tried again at the
            # next write; the database itself is fine.
            main_ok = outcome.main_ok
            all_written = main_ok and not outcome.warnings
        if (all_written and not any(jf.error for jf in check.files)
                and getattr(self.repo, "unstamped_journal_own", False)):
            # Every line of this registry now names it in every journal file.
            try:
                self.repo.journal_stamped()  # type: ignore[attr-defined]
            except RegistryError:
                pass  # e.g. a read-only database: asked again at the next write
        return main_ok

    def _journal_after_write(self, entries: list[dict[str, Any]]) -> list[str]:
        """Append the entries of a committed change; returns warnings."""
        outcome = self.journal.append(entries)
        if not outcome.main_ok:
            self._journal_verified = False  # catch up at the next write
        return outcome.warnings

    def journal_status(self) -> dict[str, Any]:
        """Read-only: the journal and what the database lacks compared with it."""
        check = self._journal_check(fresh=True)
        return {
            "path": str(self.journal.path),
            "mirror_path": str(self.journal.mirror_path) if self.journal.mirror_path else None,
            "entries": len(check.entries),
            "missing_in_database": list(check.missing_register),
            "retirements_missing_in_database": list(check.missing_retire),
            "conflicts": list(check.conflicts),
            "unreadable_lines": sum(jf.unreadable_lines for jf in check.files),
            "other_registries": check.other_registries,
        }

    # ------------------------------------------------------------------ chemistry guard
    def _chemistry_state(self) -> dict[str, Any]:
        """``{"stored", "current", "changed", "supported"}`` (cached per instance).

        A registry stores the fingerprint at its first registration and at
        every accepted ``rekey_check``. As long as none is stored, the RDKit /
        InChI versions recorded on the batches are compared instead; any
        different version counts as a change.
        """
        if self._chemistry_cache is not None:
            return self._chemistry_cache
        current = chemistry_fingerprint()
        get_meta = getattr(self.repo, "get_meta", None)
        set_meta = getattr(self.repo, "set_meta", None)
        state: dict[str, Any] = {"stored": None, "current": current, "changed": False,
                                 "supported": get_meta is not None and set_meta is not None}
        if state["supported"]:
            stored = get_meta(FINGERPRINT_KEY)  # type: ignore[misc]
            state["stored"] = stored
            if stored is not None:
                state["changed"] = stored != current
            else:
                rd, inchi = rdkit.__version__, _inchi_version()
                used = sorted({(b.rdkit_version, b.inchi_version)
                               for b in self.repo.iter_batches(include_retired=True)})
                other = [(r, i) for r, i in used if (r and r != rd) or (i and i != inchi)]
                if other:
                    state["changed"] = True
                    state["batch_versions"] = [f"rdkit={r};inchi={i}" for r, i in other]
        self._chemistry_cache = state
        return state

    @staticmethod
    def _chemistry_message(state: dict[str, Any], blocked: bool) -> str:
        if state["stored"] is not None:
            what = f"stored {state['stored']!r}, now {state['current']!r}"
        else:
            what = (f"batches were registered with {', '.join(state.get('batch_versions', []))}, "
                    f"now {state['current']!r}")
        text = (f"The chemistry software changed since the registry keys were last checked "
                f"({what}). Keys computed now could differ from the stored ones, so a known "
                f"compound could get a new ID.")
        if blocked:
            text += " Registering is blocked."
        return text + (" Run the installer again, or 'compound-registry rekey-check --accept': "
                       "it verifies every stored structure and accepts the new version when "
                       "all keys are unchanged.")

    def _ensure_chemistry(self) -> None:
        """Refuse to register with changed chemistry; store the fingerprint on
        first use."""
        state = self._chemistry_state()
        if not state["supported"]:
            return
        if state["changed"]:
            raise RegistryError(self._chemistry_message(state, blocked=True),
                                code="chemistry_version_changed")
        if state["stored"] is None:
            self.repo.set_meta(FINGERPRINT_KEY, state["current"])  # type: ignore[attr-defined]
            state["stored"] = state["current"]

    @staticmethod
    def _experiment_ref(value: object, required: bool) -> str | None:
        if value is None:
            if required:
                raise _invalid("An experiment reference is required.")
            return None
        if not isinstance(value, str):
            raise _invalid(f"experiment_ref must be text, got {value!r}")
        value = value.strip()
        if not value:
            raise _invalid("The experiment reference is blank.")
        return value

    @staticmethod
    def _optional_text(name: str, value: object) -> str | None:
        if value is None:
            return None
        if not isinstance(value, str):
            raise _invalid(f"{name} must be text, got {value!r}")
        value = value.strip()
        return value or None

    @staticmethod
    def _product_index(value: object, required: bool) -> int | None:
        if value is None and not required:
            return None
        if isinstance(value, bool) or not isinstance(value, int) or value < 1:
            raise _invalid(f"product_index must be a whole number >= 1, got {value!r}")
        return value

    def _normalize(self, molfile: str | None, smiles: str | None, mode: str | None) -> Normalized:
        """Normalise exactly one of ``molfile`` / ``smiles``.

        ``mode`` None = "as detected from the file", except that when the
        configured ``default_stereo_mode`` is not ``abs`` and the plain
        detection gives ``abs`` or ``partial`` (a drawing without enhanced
        stereo), the configured default is applied as the override. Any other
        ``mode`` goes to chemistry unchanged as ``mode_override``.
        """
        if (molfile is None) == (smiles is None):
            raise _invalid("Give exactly one structure: a molfile or a SMILES.")
        if mode is not None and mode not in MODE_OVERRIDES:
            raise ChemistryError(
                f"Unknown stereo mode {mode!r}; use one of {', '.join(MODE_OVERRIDES)}.",
                code="invalid_mode",
            )
        fn = chem.normalize if molfile is not None else chem.normalize_smiles
        text = molfile if molfile is not None else smiles
        if mode is not None:
            return fn(text, mode)
        norm = fn(text)
        default = self.config.default_stereo_mode
        if default != "abs" and norm.stereo_mode in _DEFAULTABLE_MODES:
            norm = fn(text, default)
        return norm

    def _backup_after_write(self) -> dict[str, Any]:
        outcome = backup_mod.maybe_backup(self.repo, self.config)  # never raises
        return self._outcome_dict(outcome)

    @staticmethod
    def _outcome_dict(outcome: backup_mod.BackupOutcome) -> dict[str, Any]:
        return {
            "performed": bool(outcome.performed),
            "path": str(outcome.path) if outcome.path is not None else None,
            "warning": outcome.warning,
            "removed": [str(p) for p in outcome.removed],
        }

    def _stereo_dict(self, stereo: StereoRecord, with_svg: bool) -> dict[str, Any]:
        return {
            "core_stereo_id": stereo.core_stereo_id,
            "stereo_no": stereo.stereo_no,
            "stereo_mode": stereo.stereo_mode,
            "smiles": stereo.smiles,
            "inchikey": stereo.inchikey,
            "batch_count": stereo.batch_count,
            "svg": svg_thumbnail(stereo.molfile) if with_svg else None,
        }

    def _names(self) -> dict[str, NameRecord]:
        """Every stored name (empty when the backend has no names)."""
        fn = getattr(self.repo, "get_names", None)
        return fn() if fn is not None else {}

    def _yields(self, full_ids: Iterable[str] | None = None) -> dict[str, YieldRecord]:
        """Stored yields of ``full_ids`` (or of every batch), read in one go;
        empty when the backend has no yields."""
        fn = getattr(self.repo, "get_yields", None)
        if fn is None:
            return {}
        if full_ids is None:
            return fn()
        ids = list(full_ids)
        return fn(ids) if ids else {}

    def _batch_dicts(self, batches: Iterable[BatchRecord | None],
                     with_molfile: bool = False) -> list[dict[str, Any] | None]:
        """:func:`batch_to_dict` of each batch (None stays None), each with its
        stored ``yield``; the yields are read in one go."""
        listed = list(batches)
        yields = self._yields(b.full_id for b in listed if b is not None)
        return [None if b is None else _with_yield(batch_to_dict(b, with_molfile), yields)
                for b in listed]

    def _name_of(self, core_stereo_id: str) -> dict[str, str] | None:
        fn = getattr(self.repo, "get_name", None)
        if fn is None:
            return None
        try:
            return name_dict(fn(core_stereo_id))
        except NotFoundError:
            return None

    def _inchis(self, core_stereo_ids: Iterable[str]) -> dict[str, str]:
        """Stored InChI (as drawn) of each stereo variant (empty when unsupported)."""
        fn = getattr(self.repo, "stereo_inchis", None)
        return fn(list(core_stereo_ids)) if fn is not None else {}

    def _id_format(self) -> IdFormat:
        return getattr(self.repo, "id_format", None) or IdFormat(self.config.id_format)

    # ------------------------------------------------------------------ queries
    def analyze(
        self,
        *,
        molfile: str | None = None,
        smiles: str | None = None,
        mode: str | None = None,
        experiment_ref: str | None = None,
        product_index: int | None = None,
        with_svg: bool = True,
        with_molfile: bool = False,
    ) -> dict[str, Any]:
        """Read-only: what the registry knows about this structure.

        ``status``: ``registered_here`` (an active batch of this exact compound
        exists in ``experiment_ref``; its ID is ``id``), ``known_compound``
        (this exact stereo variant is registered, but not for this
        experiment), ``known_core`` (only other stereo variants of the same
        constitution exist) or ``new``. ``name`` is the name stored for this
        stereo variant (null when there is none or it is not registered);
        ``structure.properties`` are display-only values of the drawing; each
        batch (``batches``, ``slot_conflict``) carries its stored ``yield``.
        """
        ref = self._experiment_ref(experiment_ref, required=False)
        index = self._product_index(product_index, required=False)
        norm = self._normalize(molfile, smiles, mode)
        result = self.repo.lookup(norm, ref, index if ref is not None else None)

        existing = result.existing_batch
        if existing is not None:
            status = "registered_here"
        elif result.stereo is not None:
            status = "known_compound"
        elif result.core is not None:
            status = "known_core"
        else:
            status = "new"

        svg = svg_thumbnail(norm.molblock) if with_svg else None
        *batch_dicts, conflict_dict = self._batch_dicts(
            [*result.batches, result.slot_conflict], with_molfile)
        return {
            "structure": _structure_dict(norm, svg, include_svg=True),
            "status": status,
            "id": existing.full_id if existing is not None else None,
            "core_stereo_id": result.stereo.core_stereo_id if result.stereo is not None else None,
            "core_no": result.core.core_no if result.core is not None else None,
            "name": (self._name_of(result.stereo.core_stereo_id)
                     if result.stereo is not None else None),
            "batches": batch_dicts,
            "other_stereos": [self._stereo_dict(s, with_svg) for s in result.other_stereos],
            "slot_conflict": conflict_dict,
            "mode_options": list(MODE_OVERRIDES),
            "warnings": self._read_warnings(),
        }

    def get(self, full_id: str, with_molfile: bool = False) -> dict[str, Any]:
        """The batch with this full ID; ``NotFoundError`` if there is none."""
        if not isinstance(full_id, str) or not full_id.strip():
            raise _invalid("An ID is required.")
        full_id = full_id.strip()
        batch = self.repo.get_batch(full_id)
        if batch is None:
            raise NotFoundError(f"No batch with ID {full_id!r} exists.")
        return batch_to_dict(batch, with_molfile)

    def find_by_id(self, id_text: str, with_svg: bool = True) -> dict[str, Any]:
        """Read-only: every batch, and therefore every experiment, of the
        compound an ID names.

        ``id_text`` may be a full ID (``000042_02_003``: the stereo variant
        that batch belongs to), a ``CORE_STEREO`` (``000042_02``: that stereo
        variant) or a ``CORE`` (``000042`` or ``42``: every stereo variant of
        that constitution). ``level`` says which it was: ``batch``,
        ``stereo`` or ``core``.

        ``variants``       the stereo variants the ID denotes, each with all
                           its batches (oldest first, retired included);
        ``other_variants`` the remaining stereo variants of the same CORE
                           (empty for a CORE search), without their batches;
        ``experiments``    the distinct experiments over ``variants``, in
                           order of their first batch, each with its batches.

        Every variant carries its stored ``name`` and its ``inchi`` (as
        drawn); ``variants`` also carry ``properties``. Every batch (in
        ``variants`` and in ``experiments``) carries its stored ``yield``.

        Raises ``NotFoundError`` when the text is not an ID or nothing with
        that number is registered.
        """
        if not isinstance(id_text, str) or not id_text.strip():
            raise _invalid("An ID is required.")
        text = id_text.strip()
        id_format = self._id_format()
        core_no, stereo_no, batch_no = id_format.parse_partial(text)

        by_stereo: dict[int, list[BatchRecord]] = {}
        for b in self.repo.iter_batches(include_retired=True):  # ordered by core, stereo, batch
            if b.core_no == core_no:
                by_stereo.setdefault(b.stereo_no, []).append(b)
        if not by_stereo:
            raise NotFoundError(f"Nothing is registered with CORE number {core_no} ({text!r}).")
        matched: BatchRecord | None = None
        if stereo_no is not None:
            if stereo_no not in by_stereo:
                raise NotFoundError(
                    f"CORE {core_no} has no stereo variant {stereo_no} ({text!r}); it has "
                    f"{', '.join(bs[0].core_stereo_id for bs in by_stereo.values())}.")
            if batch_no is not None:
                matched = next((b for b in by_stereo[stereo_no] if b.batch_no == batch_no), None)
                if matched is None:
                    raise NotFoundError(f"No batch with ID {text!r} exists.")
        level = "core" if stereo_no is None else ("stereo" if batch_no is None else "batch")
        chosen = sorted(by_stereo) if stereo_no is None else [stereo_no]
        names = self._names()
        inchis = self._inchis(bs[0].core_stereo_id for bs in by_stereo.values())
        yields = self._yields(b.full_id for no in chosen for b in by_stereo[no])

        def variant(batches: list[BatchRecord], full: bool) -> dict[str, Any]:
            # batches[0] is batch 1: its molfile is the variant's molfile.
            first = batches[0]
            d: dict[str, Any] = {
                "core_stereo_id": first.core_stereo_id,
                "stereo_no": first.stereo_no,
                "stereo_mode": first.stereo_mode,
                "smiles": first.smiles,
                "inchikey": first.inchikey,
                "batch_count": len(batches),
                "name": name_dict(names.get(first.core_stereo_id)),
                "inchi": inchis.get(first.core_stereo_id, ""),
            }
            if full:
                d["properties"] = compute_properties(first.molfile)
                d["svg"] = svg_thumbnail(first.molfile) if with_svg else None
                d["batches"] = [_with_yield(batch_to_dict(b), yields) for b in batches]
            return d

        experiments: dict[str, dict[str, Any]] = {}
        selected = sorted((b for no in chosen for b in by_stereo[no]),
                          key=lambda b: (b.created_at, b.core_stereo_id, b.batch_no))
        for b in selected:
            entry = experiments.setdefault(b.experiment_ref, {
                "experiment_ref": b.experiment_ref, "experiment_code": b.experiment_code,
                "experiment_url": b.experiment_url, "batches": []})
            # The newest code / link wins if the experiment was renamed.
            entry["experiment_code"] = b.experiment_code or entry["experiment_code"]
            entry["experiment_url"] = b.experiment_url or entry["experiment_url"]
            entry["batches"].append(_with_yield(
                {"full_id": b.full_id, "core_stereo_id": b.core_stereo_id,
                 "product_index": b.product_index, "created_at": b.created_at,
                 "retired": b.retired}, yields))
        return {
            "query": text,
            "level": level,
            "core_no": core_no,
            "matched_id": matched.full_id if matched is not None else None,
            "variants": [variant(by_stereo[no], True) for no in chosen],
            "other_variants": [variant(by_stereo[no], False)
                               for no in sorted(by_stereo) if no not in chosen],
            "experiments": list(experiments.values()),
            "warnings": self._read_warnings(),
        }

    def experiment(self, experiment_ref: str, with_molfile: bool = False) -> list[dict[str, Any]]:
        """All batches of one experiment (retired included), by product index."""
        ref = self._experiment_ref(experiment_ref, required=True)
        return [batch_to_dict(b, with_molfile) for b in self.repo.find_batches(ref)]

    def get_name(self, core_stereo_id: str) -> dict[str, Any]:
        """Read-only: ``{"core_stereo_id", "name"}`` (name null when none is
        stored). ``NotFoundError`` when no such stereo variant exists."""
        if not isinstance(core_stereo_id, str) or not core_stereo_id.strip():
            raise _invalid("A CORE_STEREO ID is required.")
        fn = getattr(self.repo, "get_name", None)
        if fn is None:
            raise RegistryError("This storage backend cannot store names.", code="not_supported")
        cs = core_stereo_id.strip()
        return {"core_stereo_id": cs, "name": name_dict(fn(cs))}

    # ------------------------------------------------------------------ compound list
    @staticmethod
    def _search_text(value: object) -> str | None:
        if value is None:
            return None
        if not isinstance(value, str):
            raise _invalid(f"The search text must be text, got {type(value).__name__}.")
        text = value.strip()
        if not text:
            return None
        if len(text) > protocol.MAX_SEARCH_TEXT:
            raise _invalid(f"The search text is too long (limit {protocol.MAX_SEARCH_TEXT} "
                           "characters).")
        if any(unicodedata.category(ch) == "Cc" for ch in text):
            raise _invalid("The search text must be one line without control characters.")
        return text

    @staticmethod
    def _query_text(name: str, value: object) -> str | None:
        if value is None:
            return None
        if not isinstance(value, str):
            raise _invalid(f"{name} must be text, got {type(value).__name__}.")
        if not value.strip():
            return None
        return value if name == "molfile" else value.strip()

    def compounds(
        self,
        text: str | None = None,
        molfile: str | None = None,
        smiles: str | None = None,
        match: str = "substructure",
        order: str = "asc",
        offset: int = 0,
        limit: int | None = protocol.DEFAULT_PAGE_SIZE,
        with_svg: bool = True,
    ) -> dict[str, Any]:
        """Read-only: the registered compounds, ONE ENTRY PER CORE with its
        stereo variants, optionally filtered, one page at a time.

        The search follows protocol.py, "Compound search", exactly: a CORE is
        listed when it matches ``text`` (if given) AND the query structure
        (``molfile`` or ``smiles``, compared as ``match``: ``substructure`` or
        ``exact``); ``matched_by`` says why. A text or query that cannot be
        used is not an error: ``notes`` say how the search was read.

        ``order`` sorts by CORE number (``asc`` / ``desc``); ``offset`` and
        ``limit`` select the page (``limit`` None: all the rest, for the CLI).
        Drawings, InChIs and ``properties`` are computed only for the page.
        Without the optional listing methods of the repository (see
        :mod:`compound_registry.repository`), ``not_supported`` is raised.
        """
        text = self._search_text(text)
        molfile = self._query_text("molfile", molfile)
        smiles = self._query_text("smiles", smiles)
        if molfile is not None and smiles is not None:
            raise _invalid("Give at most one query structure: a molfile or a SMILES.")
        if match not in protocol.MATCH_MODES:
            raise _invalid(f"match must be one of {', '.join(protocol.MATCH_MODES)}, got {match!r}.")
        if order not in protocol.ORDERS:
            raise _invalid(f"order must be one of {', '.join(protocol.ORDERS)}, got {order!r}.")
        if isinstance(offset, bool) or not isinstance(offset, int) or offset < 0:
            raise _invalid(f"offset must be a whole number >= 0, got {offset!r}.")
        if limit is not None and (isinstance(limit, bool) or not isinstance(limit, int)
                                  or limit < 1):
            raise _invalid(f"limit must be a whole number >= 1, got {limit!r}.")

        list_cores = getattr(self.repo, "list_cores", None)
        list_stereos = getattr(self.repo, "list_stereos", None)
        batch_summaries = getattr(self.repo, "batch_summaries", None)
        if list_cores is None or list_stereos is None or batch_summaries is None:
            raise RegistryError("This storage backend cannot list compounds.",
                                code="not_supported")

        entries: dict[int, search.CoreEntry] = {
            c.core_no: search.CoreEntry(core=c) for c in list_cores()}
        for s in list_stereos(with_molfile=False):
            entries[s.core_no].variants.append(s)
        for b in batch_summaries():
            entries[b["core_no"]].batches.append(b)
        id_format = self._id_format()

        def molfiles(core_nos: list[int]) -> dict[str, str]:
            return {s.core_stereo_id: s.molfile
                    for s in list_stereos(core_nos, with_molfile=True)}

        snap = search.Snapshot(
            entries=entries, names=self._names(), id_format=id_format,
            normalize=lambda molfile, smiles: self._normalize(molfile, smiles, None),
            lookup=lambda norm: self.repo.lookup(norm), molfiles=molfiles)

        notes: list[str] = []
        selected = list(entries)  # CORE numbers, ascending
        components: dict[int, list[search.Hit]] = {no: [] for no in selected}
        if text is not None:
            hits = search.match_text(text, snap, notes)
            selected = [no for no in selected if no in hits]
            for no in selected:
                components[no].append(hits[no])
        if molfile is not None or smiles is not None:
            hits = search.match_drawn(molfile, smiles, match, snap, selected, notes)
            selected = [no for no in selected if no in hits]
            for no in selected:
                components[no].append(hits[no])
        if order == "desc":
            selected.reverse()
        page = selected[offset:] if limit is None else selected[offset:offset + limit]

        snap.load_molfiles(page)
        inchis = self._inchis(v.core_stereo_id for no in page for v in entries[no].variants)
        items = [self._compound_item(entries[no], components[no], snap, inchis, id_format,
                                     with_svg) for no in page]
        return {
            "total": len(selected),
            "registry_total": len(entries),
            "offset": offset,
            "limit": limit if limit is not None else len(items),
            "items": items,
            "notes": list(dict.fromkeys(notes)),
            "warnings": self._read_warnings(),
        }

    @staticmethod
    def _compound_item(entry: search.CoreEntry, components: list[search.Hit],
                       snap: search.Snapshot, inchis: dict[str, str], id_format: IdFormat,
                       with_svg: bool) -> dict[str, Any]:
        first = entry.variants[0]
        molfile = snap.molfile_cache.get(first.core_stereo_id, "")
        experiments: dict[str, dict[str, Any]] = {}
        for b in entry.batches:  # oldest first
            e = experiments.setdefault(b["experiment_ref"], {
                "experiment_ref": b["experiment_ref"], "experiment_code": b["experiment_code"],
                "experiment_url": b["experiment_url"]})
            # The newest code / link wins if the experiment was renamed (as in find).
            e["experiment_code"] = b["experiment_code"] or e["experiment_code"]
            e["experiment_url"] = b["experiment_url"] or e["experiment_url"]
        reasons = set().union(*(hit.reasons for hit in components)) if components else set()
        created = [b["created_at"] for b in entry.batches]
        return {
            "core_no": entry.core.core_no,
            "core_id": id_format.format_core(entry.core.core_no),
            "formula": entry.core.formula,
            "properties": compute_properties(molfile),
            "svg": svg_thumbnail(molfile) if with_svg else None,
            "variants": [{
                "core_stereo_id": v.core_stereo_id,
                "stereo_no": v.stereo_no,
                "stereo_mode": v.stereo_mode,
                "smiles": v.smiles,
                "inchi": inchis.get(v.core_stereo_id, ""),
                "inchikey": v.inchikey,
                "name": name_dict(snap.names.get(v.core_stereo_id)),
                "batch_count": v.batch_count,
                "matched": search.variant_matched(v.stereo_no, components),
            } for v in entry.variants],
            "batch_count": len(entry.batches),
            "experiment_count": len(experiments),
            "experiments": list(experiments.values())[:protocol.MAX_ITEM_EXPERIMENTS],
            "first_created_at": min(created) if created else entry.core.created_at,
            "last_created_at": max(created) if created else entry.core.created_at,
            "matched_by": [r for r in protocol.MATCH_REASONS if r in reasons],
        }

    # ------------------------------------------------------------------ writes
    def check_writable(self, *, registering: bool = True) -> None:
        """Raise the error a write would raise because of a guard (stale
        database, journal conflict, changed chemistry when ``registering``),
        so a caller can stop before asking the user anything. It may append
        missing lines to the journal (catch-up) and store the chemistry
        fingerprint on first use; it never changes a batch."""
        self._before_write()
        if registering:
            self._ensure_chemistry()

    def register(
        self,
        *,
        molfile: str | None = None,
        smiles: str | None = None,
        mode: str | None = None,
        experiment_ref: str,
        experiment_code: str | None = None,
        experiment_url: str | None = None,
        product_index: int = 1,
        source: str = "cli",
        with_molfile: bool = False,
        accept_ignored_stereo: bool = False,
    ) -> dict[str, Any]:
        """Issue (or return) the batch ID of this compound in this experiment.

        Idempotent: the same compound in the same experiment returns the same
        ID with ``created=False``. ``SlotConflictError`` propagates. A backup
        is attempted after a new batch was created; a failed backup is
        reported as a warning, never as an error (the ID is already issued).

        Refused (nothing is written) with:

        * ``database_older_than_journal`` / ``journal_conflict`` - see
          :meth:`recover` and the module docstring;
        * ``chemistry_version_changed`` - see :meth:`rekey_check`;
        * ``stereo_not_in_key`` - the drawing has stereo features the keys do
          not contain (``structure["ignored_stereo"]`` of :meth:`analyze`) and
          ``accept_ignored_stereo`` is false. Only refused when a NEW batch
          would be created; an existing batch of this compound in this
          experiment is returned as usual.

        A new ID is appended to the issued-ID journal after the commit.
        ``accepted_ignored_stereo`` lists the ignored stereo items that were
        accepted for a NEW batch (empty otherwise).

        After every successful call (new or existing ID) the compound's
        folder is made if missing (see :mod:`compound_registry.files`):
        ``folder`` is ``{"path", "created"}``, or None when no folder could be
        made; problems with it are warnings, never errors.
        """
        ref = self._experiment_ref(experiment_ref, required=True)
        index = self._product_index(product_index, required=True)
        experiment = ExperimentRef(
            ref=ref,
            code=self._optional_text("experiment_code", experiment_code),
            url=self._optional_text("experiment_url", experiment_url),
        )
        self.check_writable(registering=True)
        norm = self._normalize(molfile, smiles, mode)
        ignored = list(norm.ignored_stereo)
        if ignored and not accept_ignored_stereo:
            # Only an existing batch may be returned: register() is not called
            # at all, so no new batch can be created without the acceptance.
            existing = self.repo.lookup(norm, ref, index).existing_batch
            if existing is None:
                raise RegistryError(ignored_stereo_message(ignored), code="stereo_not_in_key")
            repeat_warnings: tuple[str, ...] = ()
            if existing.product_index != index:
                repeat_warnings = (
                    f"This compound is already registered in this experiment as product "
                    f"{existing.product_index}; returning that ID.",
                )
            result = RegistrationResult(batch=existing, created=False, warnings=repeat_warnings)
        else:
            result = self.repo.register(norm, experiment, index, source)

        accepted = ignored if result.created else []
        warnings = list(norm.warnings) + list(result.warnings) + self._service_warnings()
        if result.created:
            b = result.batch
            entry = journal_mod.register_entry(
                b.full_id, b.created_at, experiment_ref=b.experiment_ref,
                experiment_code=b.experiment_code, experiment_url=b.experiment_url,
                product_index=b.product_index, source=b.source, norm=norm,
                accepted_ignored_stereo=accepted, registry_id=self._registry_id())
            warnings.extend(self._journal_after_write([entry]))
            backup = self._backup_after_write()
        else:
            backup = {"performed": False, "path": None, "warning": None, "removed": []}
        if backup["warning"]:
            warnings.append(backup["warning"])
        # The compound's folder (never fails or undoes the registration).
        folder, folder_warning = self._ensure_folder(result.batch.core_stereo_id,
                                                     fallback_molfile=result.batch.molfile)
        if folder_warning:
            warnings.append(folder_warning)
        return {
            "id": result.batch.full_id,
            "created": bool(result.created),
            "core_created": bool(result.core_created),
            "stereo_created": bool(result.stereo_created),
            "batch": self._batch_dicts([result.batch], with_molfile)[0],
            "structure": _structure_dict(norm, None, include_svg=False),
            "accepted_ignored_stereo": accepted,
            "warnings": list(dict.fromkeys(warnings)),
            "backup": backup,
            "folder": folder,
        }

    def retire(self, full_id: str, reason: str) -> dict[str, Any]:
        """Retire a batch (its number stays taken forever), journal it, then
        back up. Refused like :meth:`register` when the database is older
        than the journal."""
        if not isinstance(full_id, str) or not full_id.strip():
            raise _invalid("An ID is required.")
        self.check_writable(registering=False)
        batch = self.repo.retire(full_id.strip(), reason)
        warnings = self._service_warnings()
        warnings.extend(self._journal_after_write([journal_mod.retire_entry(
            batch.full_id, batch.retired_at or "", batch.retired_reason or "",
            self._registry_id())]))
        backup = self._backup_after_write()
        if backup["warning"]:
            warnings.append(backup["warning"])
        return {"id": batch.full_id, "batch": self._batch_dicts([batch])[0], "warnings": warnings,
                "backup": backup}

    def set_name(self, core_stereo_id: str, name: str | None) -> dict[str, Any]:
        """Store (text) or remove (None) the name of a stereo variant; returns
        ``{"core_stereo_id", "name", "changed", "warnings"}``.

        A name is an annotation, not an ID: it is written even while the
        guards block registering (stale database, changed chemistry), and it
        is not written to the issued-ID journal; the registry's event log
        records every change. After a change the automatic backup runs; its
        warning is reported. ``NotFoundError`` for an unknown CORE_STEREO;
        ``invalid_argument`` for a blank, multi-line or too long name (see
        :func:`clean_name`).
        """
        if not isinstance(core_stereo_id, str) or not core_stereo_id.strip():
            raise _invalid("A CORE_STEREO ID is required.")
        cs = core_stereo_id.strip()
        text = clean_name(name)
        setter = getattr(self.repo, "set_name", None)
        if setter is None:
            raise RegistryError("This storage backend cannot store names.", code="not_supported")
        record, changed = setter(cs, text, source="user")
        warnings = self._service_warnings()
        if changed:
            backup = self._backup_after_write()
            if backup["warning"]:
                warnings.append(backup["warning"])
        return {"core_stereo_id": cs, "name": name_dict(record), "changed": bool(changed),
                "warnings": warnings}

    # ------------------------------------------------------------------ yields
    def set_yield(self, full_id: str, experiment_ref: str, product_index: int,
                  isolated: float | None, analytical: float | None) -> dict[str, Any]:
        """Store the yields of a batch as the ELN shows them (both None:
        remove the stored yield); returns ``{"id", "yield", "changed",
        "warnings"}`` with ``yield`` as stored after the call (see
        protocol.py, "Yields").

        ``experiment_ref`` and ``product_index`` say where the yields were
        read; unless the batch was registered for exactly that experiment and
        product row, nothing is written and ``RegistryError(code=
        "yield_mismatch")`` is raised. Each value is None or a number of
        percent from 0 to :data:`protocol.MAX_YIELD_PERCENT`, rounded to two
        decimals (else ``invalid_argument``). ``NotFoundError`` for an unknown
        ID. A retired batch may get a yield.

        Like :meth:`set_name`: written even while the guards block
        registering, not written to the issued-ID journal, recorded in the
        event log, followed by the automatic backup after a change.
        """
        if not isinstance(full_id, str) or not full_id.strip():
            raise _invalid("An ID is required.")
        fid = full_id.strip()
        ref = self._experiment_ref(experiment_ref, required=True)
        index = self._product_index(product_index, required=True)
        values = {kind: clean_yield(kind, value) for kind, value in
                  zip(protocol.YIELD_KINDS, (isolated, analytical))}
        setter = getattr(self.repo, "set_yield", None)
        if setter is None:
            raise RegistryError("This storage backend cannot store yields.", code="not_supported")
        batch = self.repo.get_batch(fid)
        if batch is None:
            raise NotFoundError(f"No batch with ID {fid!r} exists.")
        if batch.experiment_ref != ref or batch.product_index != index:
            where = batch.experiment_code or "the experiment"
            raise RegistryError(
                f"{fid} was registered for product {batch.product_index} of {where} (internal "
                f"key {batch.experiment_ref}), but these yields were read from product {index} "
                f"of the experiment with internal key {ref}. They belong to another product, "
                f"so nothing was stored for {fid}.",
                code="yield_mismatch")
        record, changed = setter(fid, values["isolated"], values["analytical"])
        warnings = self._service_warnings()
        if changed:
            backup = self._backup_after_write()
            if backup["warning"]:
                warnings.append(backup["warning"])
        return {"id": fid, "yield": yield_dict(record), "changed": bool(changed),
                "warnings": warnings}

    def yields(self, text: str | None = None, only_recorded: bool = False, order: str = "asc",
               offset: int = 0,
               limit: int | None = protocol.DEFAULT_YIELD_PAGE_SIZE) -> dict[str, Any]:
        """Read-only: ONE ROW PER BATCH (retired ones included) with its
        experiment and its yield, one page at a time; returns ``{"total",
        "registry_total", "offset", "limit", "items", "warnings"}`` as
        protocol.py, "Yields", describes.

        Rows are ordered by ELN number (digit runs compared as numbers),
        batches without an ELN number last by their internal key, then by
        product number, then by full ID; ``order="desc"`` reverses the whole
        order. ``text`` keeps a row when it occurs (ignoring case) in its ELN
        number, full ID or name, or equals its internal experiment key;
        ``only_recorded`` keeps only rows with a yield. ``limit`` None: all
        the rest (for the CLI). As in ``find``, an experiment shows the
        newest ELN number and link stored with any of its batches.
        """
        text = self._search_text(text)
        if not isinstance(only_recorded, bool):
            raise _invalid("'only_recorded' must be true or false.")
        if order not in protocol.ORDERS:
            raise _invalid(f"order must be one of {', '.join(protocol.ORDERS)}, got {order!r}.")
        if isinstance(offset, bool) or not isinstance(offset, int) or offset < 0:
            raise _invalid(f"offset must be a whole number >= 0, got {offset!r}.")
        if limit is not None and (isinstance(limit, bool) or not isinstance(limit, int)
                                  or limit < 1):
            raise _invalid(f"limit must be a whole number >= 1, got {limit!r}.")
        lister = getattr(self.repo, "batch_yields", None)
        if lister is None:
            raise RegistryError("This storage backend cannot list yields.", code="not_supported")
        rows = lister()  # oldest first
        experiments: dict[str, dict[str, Any]] = {}
        for r in rows:
            e = experiments.setdefault(r["experiment_ref"], {"code": None, "url": None})
            # The newest code / link wins if the experiment was renamed (as in find).
            e["code"] = r["experiment_code"] or e["code"]
            e["url"] = r["experiment_url"] or e["url"]
        items = [{
            "experiment_ref": r["experiment_ref"],
            "experiment_code": experiments[r["experiment_ref"]]["code"],
            "experiment_url": experiments[r["experiment_ref"]]["url"],
            "product_index": r["product_index"],
            "full_id": r["full_id"],
            "core_stereo_id": r["core_stereo_id"],
            "name": r["name"],
            "yield": yield_dict(r["yield"]),
            "created_at": r["created_at"],
            "retired": bool(r["retired"]),
        } for r in rows]
        registry_total = len(items)
        if text is not None:
            folded = text.casefold()
            items = [i for i in items
                     if i["experiment_ref"] == text
                     or any(value and folded in value.casefold()
                            for value in (i["experiment_code"], i["full_id"], i["name"]))]
        if only_recorded:
            items = [i for i in items if i["yield"] is not None]

        def sort_key(i: dict[str, Any]) -> tuple[Any, ...]:
            code, ref = i["experiment_code"], i["experiment_ref"]
            if code:
                return (0, _natural_key(code), code, _natural_key(ref), ref,
                        i["product_index"], i["full_id"])
            return (1, _natural_key(ref), ref, (), "", i["product_index"], i["full_id"])

        items.sort(key=sort_key, reverse=(order == "desc"))
        page = items[offset:] if limit is None else items[offset:offset + limit]
        return {
            "total": len(items),
            "registry_total": registry_total,
            "offset": offset,
            "limit": limit if limit is not None else len(page),
            "items": page,
            "warnings": self._read_warnings(),
        }

    def record_spectra(self, full_id: str, spectra: Any) -> dict[str, Any]:
        """Store what was measured for a batch (sent by the MestReNova
        add-on): ``spectra`` is a list of objects, see
        :func:`compound_registry.spectra.clean_spectrum`. Returns ``{"id",
        "spectra": [{"spectrum_key", "data", "updated_at", "changed"}],
        "changed": N, "warnings"}``.

        Like a name this is an annotation: written even while the guards
        block registering, not written to the issued-ID journal, recorded in
        the event log, followed by the automatic backup when something
        changed. A spectrum recorded again (same dataset name, nucleus and
        dimension) replaces the earlier record. ``NotFoundError`` for an
        unknown ID; ``invalid_argument`` for malformed data (then nothing of
        the call is stored).
        """
        from .spectra import clean_spectrum

        if not isinstance(full_id, str) or not full_id.strip():
            raise _invalid("An ID is required.")
        if not isinstance(spectra, list) or not spectra:
            raise _invalid("A non-empty list of spectra is required.")
        if len(spectra) > 50:
            raise _invalid(f"Too many spectra in one call ({len(spectra)}, limit 50).")
        recorder = getattr(self.repo, "record_spectrum", None)
        if recorder is None:
            raise RegistryError("This storage backend cannot store spectra.", code="not_supported")
        cleaned = [clean_spectrum(raw) for raw in spectra]       # all checked before any write
        if self.repo.get_batch(full_id.strip()) is None:
            raise NotFoundError(f"No batch {full_id.strip()!r} is registered.")
        stored, n_changed = [], 0
        for key, data in cleaned:
            record, changed = recorder(full_id.strip(), key, data)
            n_changed += bool(changed)
            stored.append({"spectrum_key": record["spectrum_key"], "data": record["data"],
                           "updated_at": record["updated_at"], "changed": bool(changed)})
        warnings = self._service_warnings()
        if n_changed:
            backup = self._backup_after_write()
            if backup["warning"]:
                warnings.append(backup["warning"])
        return {"id": full_id.strip(), "spectra": stored, "changed": n_changed,
                "warnings": warnings}

    def spectra(self, id_text: str | None = None) -> dict[str, Any]:
        """Read-only: the recorded spectra of a batch (full ID), of every
        batch of a stereo variant (``CORE_STEREO``) or, without an ID, of the
        whole registry: ``{"id", "spectra": [{"full_id", "spectrum_key",
        "data", "updated_at"}]}``. An ID nothing is recorded for gives an
        empty list."""
        reader = getattr(self.repo, "get_spectra", None)
        if reader is None:
            raise RegistryError("This storage backend cannot store spectra.", code="not_supported")
        if id_text is None or not str(id_text).strip():
            return {"id": None, "spectra": reader()}
        text = str(id_text).strip()
        found = reader(full_id=text)
        if not found:
            found = reader(core_stereo_id=text)
        return {"id": text, "spectra": found}

    def recorded_file(self, full_id: str, stored: Any) -> str | None:
        """Read-only: where a file recorded with a spectrum of the batch
        ``full_id`` (``mnova_file`` or ``pdf_file`` of its data) lies now: at
        the recorded path or, when the files folder was moved since, under
        the same name in the compound's folder. None when it is in neither
        place."""
        batch = self.repo.get_batch(full_id.strip()) if isinstance(full_id, str) else None
        if batch is None:
            return None
        path = files_mod.resolve_recorded(self.config.files_dir, batch.core_stereo_id, stored)
        try:
            return str(path) if path is not None and path.is_file() else None
        except (OSError, ValueError):
            return None

    def generate_name(self, core_stereo_id: str, replace: bool = False) -> dict[str, Any]:
        """Get the name of a stereo variant from the local naming program
        (ChemDraw) and store it with source ``chemdraw``; returns
        ``{"core_stereo_id", "name", "generated", "changed", "message",
        "warnings"}``.

        ``name`` is the name stored after the call (or None). ``generated`` is
        true when a name was obtained and stored (``changed`` false when
        exactly that generated name was already stored). Otherwise
        ``message`` says in plain words why not: a name is already stored and
        ``replace`` is false (then the naming program is not asked at all),
        there is no naming program, or its answer could not be trusted (see
        :mod:`compound_registry.naming`). Not getting a name is not an error.

        Like :meth:`set_name` this works while the guards block registering,
        writes nothing to the issued-ID journal, and runs the automatic backup
        after a change. ``NotFoundError`` for an unknown CORE_STEREO. May take
        up to about :data:`protocol.NAME_GENERATION_TIMEOUT_S` seconds.
        """
        return self._generate_name(core_stereo_id, replace)[0]

    def _generate_name(self, core_stereo_id: str, replace: bool) -> tuple[dict[str, Any], str]:
        """:meth:`generate_name` plus the outcome code (``naming.NameOutcome.code``,
        or ``kept`` when an existing name was kept)."""
        if not isinstance(core_stereo_id, str) or not core_stereo_id.strip():
            raise _invalid("A CORE_STEREO ID is required.")
        if not isinstance(replace, bool):
            raise _invalid("'replace' must be true or false.")
        cs = core_stereo_id.strip()
        getter = getattr(self.repo, "get_name", None)
        setter = getattr(self.repo, "set_name", None)
        stereo_of = getattr(self.repo, "get_stereo", None)
        if getter is None or setter is None or stereo_of is None:
            raise RegistryError("This storage backend cannot store names.", code="not_supported")
        stereo = stereo_of(cs)
        if stereo is None:
            raise NotFoundError(f"No stereo variant {cs!r} is registered.")
        current = getter(cs)
        warnings = self._service_warnings()

        def result(record: NameRecord | None, generated: bool, changed: bool,
                   message: str | None, code: str) -> tuple[dict[str, Any], str]:
            return ({"core_stereo_id": cs, "name": name_dict(record), "generated": generated,
                     "changed": changed, "message": message, "warnings": warnings}, code)

        if current is not None and not replace:
            return result(current, False, False,
                          f"A name is already stored for {cs}; it was kept.", "kept")
        outcome = naming.generate(stereo.molfile, stereo.stereo_key, ask=self.name_asker)
        if outcome.name is None:
            return result(current, False, False,
                          outcome.message or f"{outcome.tool} gave no name for {cs}.",
                          outcome.code)
        try:
            text = clean_name(outcome.name)
        except RegistryError:
            return result(current, False, False,
                          f"{outcome.tool} returned a name that cannot be stored (it is not one "
                          "line of text). You can still type or paste the name.", "rejected")
        record, changed = setter(cs, text, source="chemdraw")
        if changed:
            backup = self._backup_after_write()
            if backup["warning"]:
                warnings.append(backup["warning"])
        return result(record, True, bool(changed), None, outcome.code)

    def generate_names(self, limit: int | None = None,
                       progress: Callable[[dict[str, Any]], None] | None = None) -> dict[str, Any]:
        """Try :meth:`generate_name` for every stereo variant that has no stored
        name (by CORE, then STEREO number), at most ``limit`` of them.

        Returns ``{"tried", "generated", "remaining", "results", "stopped",
        "warnings"}``: ``results`` holds each :meth:`generate_name` result in
        order (``progress`` is also called with each as soon as it is there);
        ``remaining`` is how many unnamed variants were not tried; ``stopped``
        is None, or the reason the run ended early (no naming program on this
        PC: every further variant would fail the same way).
        """
        if limit is not None and (isinstance(limit, bool) or not isinstance(limit, int)
                                  or limit < 1):
            raise _invalid("The limit must be a whole number of at least 1.")
        lister = getattr(self.repo, "list_stereos", None)
        if lister is None or getattr(self.repo, "get_names", None) is None:
            raise RegistryError("This storage backend cannot store names.", code="not_supported")
        named = self._names()
        todo = [s.core_stereo_id for s in lister(with_molfile=False)
                if s.core_stereo_id not in named]
        results: list[dict[str, Any]] = []
        stopped: str | None = None
        for cs in todo[:limit] if limit is not None else todo:
            entry, code = self._generate_name(cs, False)
            results.append(entry)
            if progress is not None:
                progress(entry)
            if code == "unavailable":
                stopped = entry["message"]
                break
        warnings: list[str] = []
        for entry in results:
            warnings.extend(entry["warnings"])
        return {"tried": len(results), "generated": sum(1 for r in results if r["generated"]),
                "remaining": len(todo) - len(results), "results": results, "stopped": stopped,
                "warnings": list(dict.fromkeys(warnings))}

    def recover_plan(self) -> dict[str, Any]:
        """Read-only: what :meth:`recover` would re-create (``to_register``,
        ``to_retire``, ``already_present``, ``conflicts``, ``journal``)."""
        check = self._journal_check(fresh=True)
        return {
            "to_register": list(check.missing_register),
            "to_retire": list(check.missing_retire),
            "already_present": check.already_present,
            "conflicts": list(check.conflicts),
            "journal": str(self.journal.path),
            "other_registries": check.other_registries,
        }

    def recover(self) -> dict[str, Any]:
        """Re-create, in journal order, the registrations and retirements the
        journal holds but the database lacks (after restoring an old backup).

        No chemistry is recomputed: each registration is rebuilt from its
        journal entry, keeps its original timestamp and must receive exactly
        its journalled ID. Everything happens in ONE transaction: if any ID
        cannot be reproduced, nothing is changed and
        ``RegistryError(code="recover_failed")`` names the ID.

        Returns ``{"recovered": [ids], "retired": [ids], "already_present": n,
        "warnings": [...], "backup": {...}}``.
        """
        check = self._journal_check(fresh=True)
        if check.shared:
            raise RegistryError(self._shared_message(check) + " Nothing was changed.",
                                code="journal_shared")
        if check.conflicts:
            raise RegistryError(
                self._conflict_message(check) + " Recover cannot repair this; nothing was changed.",
                code="recover_failed")
        replay = getattr(self.repo, "replay", None)
        if replay is None:
            raise RegistryError("This storage backend cannot recover from the journal.",
                                code="recover_failed")
        missing_register = set(check.missing_register)
        missing_retire = set(check.missing_retire)
        operations: list[ReplayRegister | ReplayRetire] = []
        for entry in check.entries:
            full_id = entry["id"]
            try:
                if entry["event"] == "register" and full_id in missing_register:
                    operations.append(ReplayRegister(
                        norm=journal_mod.normalized_from_entry(entry),
                        experiment=ExperimentRef(ref=entry["experiment_ref"],
                                                 code=entry.get("experiment_code"),
                                                 url=entry.get("experiment_url")),
                        product_index=entry["product_index"],
                        source=entry["source"],
                        created_at=entry["at"],
                        expect_full_id=full_id,
                    ))
                elif entry["event"] == "retire" and full_id in missing_retire:
                    operations.append(ReplayRetire(full_id=full_id, reason=entry["reason"],
                                                   retired_at=entry["at"]))
            except (KeyError, TypeError) as exc:
                raise RegistryError(
                    f"The journal entry for {full_id} ({entry['event']}) is incomplete ({exc}), "
                    "so it cannot be re-created exactly. Nothing was changed.",
                    code="recover_failed") from None
        recovered: list[str] = []
        retired: list[str] = []
        if operations:
            try:
                replay(operations)
            except RegistryError as exc:
                failed = getattr(exc, "failed_id", None)
                which = f"{failed} could not be reproduced exactly" if failed else "recovery failed"
                raise RegistryError(
                    f"Recovery stopped: {which}. {exc.message} Nothing was changed: the "
                    "database is exactly as before. Do not register anything; restore a "
                    "more recent backup or ask for help.",
                    code="recover_failed") from None
            recovered = [op.expect_full_id for op in operations if isinstance(op, ReplayRegister)]
            retired = [op.full_id for op in operations if isinstance(op, ReplayRetire)]
        # The database now holds everything: verify, and catch up the journal files.
        self._journal_verified = False
        self._journal_check_cache = None
        self._chemistry_cache = None
        try:
            self._before_write()
        except RegistryError as exc:
            raise RegistryError(f"After recovery the journal still does not match the "
                                f"database: {exc.message}", code="recover_failed") from None
        warnings = self._service_warnings()
        backup = (self._backup_after_write() if operations
                  else {"performed": False, "path": None, "warning": None, "removed": []})
        if backup["warning"]:
            warnings.append(backup["warning"])
        return {"recovered": recovered, "retired": retired,
                "already_present": check.already_present, "warnings": warnings,
                "backup": backup}

