CREATE_BREAKAWAY_FROM_JOB = 0x01000000
CREATE_NO_WINDOW = 0x08000000

# How long open_outside_job waits for its helper to hand the file to Windows.
_OPEN_HELPER_TIMEOUT = 20.0

# The helper's whole program: ask Windows to open the file named on its
# command line (a Python traceback on stderr and exit code 1 when it cannot).
_OPEN_HELPER = "import os, sys; os.startfile(sys.argv[1])"


def open_outside_job(path: str, popen: Callable[..., Any] = subprocess.Popen,
                     executable: str | None = None) -> None:
    """Ask Windows to open ``path`` (ChemDraw opens .cdxml) from a process
    that is NOT inside the native host's Job object. Raises ``OSError`` when
    the file could not be handed to Windows.

    Why: the browser runs the native host inside a Windows Job object and
    kills the whole job when it closes the host (the extension disconnects
    when it goes idle, and the browser closes the host when it quits). A
    program opened
    straight from the host (``os.startfile``) starts inside that job, so the
    ChemDraw window - and any edits made in it - would be killed with the
    host. Hence:

    * a small helper Python (``executable``, by default this Python) is
      started with ``CREATE_BREAKAWAY_FROM_JOB`` and calls ``os.startfile``;
      ChemDraw then starts outside the job. The helper is waited for (up to
      20 seconds) so that "no program opens .cdxml files" is still reported;
      if it takes longer, the file counts as handed over.
    * if the helper cannot be started that way (the job refuses breakaway,
      or the Python cannot be found), ``explorer.exe`` is asked to open the
      file instead: it hands the file to the running Windows shell, which
      starts ChemDraw outside the job. Explorer reports nothing back.

    The helper never gets the host's stdin/stdout (they carry the native
    messages). ``popen`` is replaceable for tests.
    """
    quiet = {"stdin": subprocess.DEVNULL, "stdout": subprocess.DEVNULL}
    python = executable if executable is not None else sys.executable
    helper = None
    if python:
        try:
            helper = popen([python, "-I", "-c", _OPEN_HELPER, path], stderr=subprocess.PIPE,
                           creationflags=CREATE_BREAKAWAY_FROM_JOB | CREATE_NO_WINDOW,
                           close_fds=True, **quiet)
        except (OSError, ValueError):
            helper = None
    if helper is None:
        # A Windows path never holds '"', so quoting it whole is safe; the
        # quotes also keep explorer from reading a ',' in it as a switch.
        popen(f'explorer.exe "{path}"', stderr=subprocess.DEVNULL,
              creationflags=CREATE_NO_WINDOW, close_fds=True, **quiet)
        return
    try:
        _out, err = helper.communicate(timeout=_OPEN_HELPER_TIMEOUT)
    except subprocess.TimeoutExpired:
        return      # still busy (a slow program); it runs outside the job anyway
    if helper.returncode:
        text = err.decode("utf-8", "replace") if isinstance(err, bytes) else str(err or "")
        lines = [line.strip() for line in text.splitlines() if line.strip()]
        reason = lines[-1] if lines else f"the helper ended with code {helper.returncode}"
        # "OSError: [WinError 1155] No application is associated ...: 'C:\\...'"
        reason = re.sub(r"^\w*(?:Error|Exception)\w*:\s*", "", reason)
        reason = re.sub(r"^\[WinError \d+\]\s*", "", reason)
        raise OSError(reason.split(": '")[0].rstrip("."))


def open_with_system(path: str, popen: Callable[..., Any] = subprocess.Popen,
                     command: str = "open") -> None:
    """Ask macOS to open ``path`` with the program for its file type
    (``open <path>``). Raises ``OSError`` when it could not be handed over.

    The command runs in a session of its own and never gets the host's
    stdin/stdout/stderr (they carry the native messages). ``popen`` is
    replaceable for tests."""
    proc = popen([command, path], stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                 stderr=subprocess.DEVNULL, close_fds=True, start_new_session=True)
    try:
        code = proc.wait(timeout=_OPEN_HELPER_TIMEOUT)
    except subprocess.TimeoutExpired:
        return      # still busy; it runs on its own
    if code:
        raise OSError(f"no program opened it ('{command}' ended with code {code})")


